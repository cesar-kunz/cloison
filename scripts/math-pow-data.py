"""src/math_pow_data.rs: the tables of `Math.pow` (src/math.rs's `pow`),
from Arm Optimized Routines' `math/pow_log_data.c` and `math/exp_data.c`
(v23.01; MIT OR Apache-2.0 WITH LLVM-exception), as glibc and musl carry
them too: their 128-entry configuration (`POW_LOG_TABLE_BITS` and
`EXP_TABLE_BITS` 7, `POW_LOG_POLY_ORDER` 8, `EXP_POLY_ORDER` 5).

The doubles are written as their bits, since Rust has no hexadecimal
floating-point literals.

    git clone https://github.com/ARM-software/optimized-routines
    python3 -I scripts/math-pow-data.py optimized-routines/math
"""
import os, re, struct, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEXF = r'-?0x[0-9a-f.]+p[-+]?[0-9]+'


def bits(x):
    return '0x%016x' % struct.unpack('<Q', struct.pack('<d', x))[0]


def field(src, name):
    """`.name = <hex float>[ * N]`, the first one in `src`."""
    m = re.search(r'\.%s = (%s)( \* N)?,' % (name, HEXF), src)
    return float.fromhex(m.group(1)) * (128 if m.group(2) else 1)


def branch(src, cond):
    """The lines of the `#if`/`#elif` branch whose condition is `cond`."""
    lines = src.split(cond + '\n', 1)[1].splitlines()
    end = next(i for i, l in enumerate(lines) if l.startswith('#'))
    return lines[:end]


log = open(os.path.join(sys.argv[1], 'pow_log_data.c')).read()
exp = open(os.path.join(sys.argv[1], 'exp_data.c')).read()

# The log polynomial's coefficients come scaled (`0x1.5p-2 * -2`).
poly = []
for line in branch(log, '#if N == 128 && POW_LOG_POLY_ORDER == 8'):
    m = re.match(r'(%s)(?: \* (-?\d+))?,' % HEXF, line)
    if m:
        poly.append(float.fromhex(m.group(1)) * int(m.group(2) or 1))
assert len(poly) == 7
tab = [tuple(float.fromhex(v) for v in m.groups()) for m in re.finditer(r'^A\((%s), (%s), (%s)\)' % (HEXF, HEXF, HEXF), log, re.M)]
assert len(tab) == 128

exp_poly = [float.fromhex(l.rstrip(',')) for l in branch(exp, '#elif N == 128 && EXP_POLY_ORDER == 5 && !EXP_POLY_WIDE') if l.startswith('0x')]
assert len(exp_poly) == 4
exp_tab = []
for line in branch(exp.split('.tab = {', 1)[1], '#elif N == 128'):
    exp_tab += [int(v, 16) for v in re.findall(r'0x[0-9a-f]+', line)]
assert len(exp_tab) == 256

out = [
    '// Generated by scripts/math-pow-data.py from Arm Optimized Routines',
    "// v23.01's math/pow_log_data.c and math/exp_data.c (Copyright (c) 2018,",
    "// Arm Limited; MIT OR Apache-2.0 WITH LLVM-exception): don't edit.",
    '',
    '/// `ln 2`, in two parts.',
    f'pub(crate) const LN2_HI: f64 = f64::from_bits({bits(field(log, "ln2hi"))});',
    f'pub(crate) const LN2_LO: f64 = f64::from_bits({bits(field(log, "ln2lo"))});',
    '/// The polynomial of `log1p(r) - r`, from its `r^2` term, scaled as its',
    '/// evaluation wants.',
    'pub(crate) const LOG_POLY: [f64; 7] = [',
]
out += [f'    f64::from_bits({bits(c)}),' for c in poly]
out += [
    '];',
    '/// For each of the 128 intervals of `z`: `1/c`, and `log(c)` in two parts',
    '/// (`c` is near the interval\'s centre).',
    'pub(crate) static LOG_TAB: [[f64; 3]; 128] = [',
]
out += [f'    [f64::from_bits({bits(a)}), f64::from_bits({bits(b)}), f64::from_bits({bits(c)})],' for a, b, c in tab]
out += [
    '];',
    '/// `128/ln 2`, and `-ln 2/128` in two parts.',
    f'pub(crate) const INV_LN2_N: f64 = f64::from_bits({bits(field(exp, "invln2N"))});',
    f'pub(crate) const NEG_LN2_HI_N: f64 = f64::from_bits({bits(float.fromhex(branch(exp, "#elif N == 128")[0].split(" = ")[1].rstrip(",")))});',
    f'pub(crate) const NEG_LN2_LO_N: f64 = f64::from_bits({bits(float.fromhex(branch(exp, "#elif N == 128")[1].split(" = ")[1].rstrip(",")))});',
    "/// The polynomial of `exp(r) - 1 - r`, from its `r^2` term.",
    'pub(crate) const EXP_POLY: [f64; 4] = [',
]
out += [f'    f64::from_bits({bits(c)}),' for c in exp_poly]
out += [
    '];',
    '/// For `k` in `0..128`, a pair: the bits of the tail of `2^(k/128)`, and',
    '/// the bits of `2^(k/128)` less `k << 45` (so that adding `k << 45`',
    '/// makes the exponent).',
    'pub(crate) static EXP_TAB: [u64; 256] = [',
]
out += [f'    0x{a:016x}, 0x{b:016x},' for a, b in zip(exp_tab[::2], exp_tab[1::2])]
out.append('];')
open(os.path.join(ROOT, 'src/math_pow_data.rs'), 'w').write('\n'.join(out) + '\n')
print(f'{len(tab)} log entries, {len(exp_tab) // 2} exp entries')
