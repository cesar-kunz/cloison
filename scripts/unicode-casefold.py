"""src/unicode_casefold.rs: Unicode's simple case folding, from
CaseFolding.txt's common (C) and simple (S) mappings, for the regexp
canonicalization of `u` and `v` mode with `i` (Canonicalize: scf).

The table is the code points that fold to another, sorted, each with its
folding; the others fold to themselves. Its Unicode version is the one
`String.prototype.toUpperCase` and `toLowerCase` use (the toolchain's
`char` tables, `char::UNICODE_VERSION`), so that case agrees between them.

    curl -O https://www.unicode.org/Public/18.0.0/ucd/CaseFolding.txt
    python3 -I scripts/unicode-casefold.py CaseFolding.txt
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(sys.argv[1], encoding='utf-8').read()
version = re.match(r'# CaseFolding-([0-9.]+)\.txt', src).group(1)
folds = []
for line in src.splitlines():
    line = line.split('#')[0].strip()
    if not line:
        continue
    code, status, mapping = [f.strip() for f in line.split(';')[:3]]
    if status in ('C', 'S'):
        folds.append((int(code, 16), int(mapping, 16)))
folds.sort()
out = [
    f'// Generated by scripts/unicode-casefold.py from CaseFolding-{version}.txt',
    "// (its C and S mappings): don't edit.",
    '',
    '/// The code points simple case folding changes, sorted, each with its',
    '/// folding.',
    f'pub(crate) static SIMPLE: [(u32, u32); {len(folds)}] = [',
]
out += [f'    (0x{a:X}, 0x{b:X}),' for a, b in folds]
out.append('];')
open(os.path.join(ROOT, 'src/unicode_casefold.rs'), 'w').write('\n'.join(out) + '\n')
print(f'{len(folds)} foldings (Unicode {version})')
