"""src/unicode_norm.rs: the tables `String.prototype.normalize` uses (see
`crate::normalize`), from the Unicode Character Database.

From UnicodeData.txt, each code point's canonical combining class (other
than 0) and decomposition mapping (one level, canonical or compatibility;
Hangul syllables are decomposed algorithmically, so not listed); from
DerivedNormalizationProps.txt, the code points excluded from composition
(Full_Composition_Exclusion): the pairs a canonical decomposition of two
composes back from are the others'.

    curl -O https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt
    curl -O https://www.unicode.org/Public/17.0.0/ucd/DerivedNormalizationProps.txt
    python3 -I scripts/unicode-norm.py <the directory they're in>
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UCD = sys.argv[1]

version = re.search(r'DerivedNormalizationProps-([\d.]+)\.txt', open(os.path.join(UCD, 'DerivedNormalizationProps.txt')).readline()).group(1)

ccc, decomp = {}, {}
for line in open(os.path.join(UCD, 'UnicodeData.txt')):
    f = line.split(';')
    cp = int(f[0], 16)
    if int(f[3]):
        ccc[cp] = int(f[3])
    if f[5]:
        d = f[5].split()
        compat = d[0].startswith('<')
        decomp[cp] = (compat, [int(x, 16) for x in (d[1:] if compat else d)])

excluded = set()
for line in open(os.path.join(UCD, 'DerivedNormalizationProps.txt')):
    m = re.match(r'([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*Full_Composition_Exclusion\b', line)
    if m:
        a = int(m.group(1), 16)
        excluded.update(range(a, int(m.group(2) or m.group(1), 16) + 1))

# Combining classes as ranges of one class.
cranges = []
for cp in sorted(ccc):
    if cranges and cranges[-1][1] == cp - 1 and cranges[-1][2] == ccc[cp]:
        cranges[-1][1] = cp
    else:
        cranges.append([cp, cp, ccc[cp]])

data, entries = [], []
for cp in sorted(decomp):
    compat, d = decomp[cp]
    entries.append((cp, len(data), len(d), compat))
    data.extend(d)

pairs = sorted(
    (d[0], d[1], cp) for cp, (compat, d) in decomp.items() if not compat and len(d) == 2 and cp not in excluded
)

out = [
    f'// Generated by scripts/unicode-norm.py from the Unicode Character Database\n// ({version}): don\'t edit.\n',
    '/// Canonical combining classes other than 0: sorted inclusive ranges\n/// of one class.',
    f'pub(crate) static CCC: [(u32, u32, u8); {len(cranges)}] = [',
]
out += [f'    (0x{a:X}, 0x{b:X}, {c}),' for a, b, c in cranges]
out += [
    '];\n',
    '/// Decomposition mappings, one level, by code point (sorted): where the\n/// mapping starts in [`DATA`], its length, and whether it is a\n/// compatibility one.',
    f'pub(crate) static DECOMP: [(u32, u16, u8, bool); {len(entries)}] = [',
]
out += [f'    (0x{cp:X}, {at}, {n}, {"true" if c else "false"}),' for cp, at, n, c in entries]
out += ['];\n', '/// The mappings\' code points.', f'pub(crate) static DATA: [u32; {len(data)}] = [']
for i in range(0, len(data), 12):
    out.append('    ' + ' '.join(f'0x{x:X},' for x in data[i:i + 12]))
out += [
    '];\n',
    '/// Canonical compositions: a starter, the code point it composes with,\n/// and their composite, sorted (composites excluded from composition\n/// left out).',
    f'pub(crate) static COMPOSE: [(u32, u32, u32); {len(pairs)}] = [',
]
out += [f'    (0x{a:X}, 0x{b:X}, 0x{c:X}),' for a, b, c in pairs]
out.append('];')
open(os.path.join(ROOT, 'src/unicode_norm.rs'), 'w').write('\n'.join(out) + '\n')
print(len(cranges), 'class ranges,', len(entries), 'decompositions,', len(data), 'code points,', len(pairs), 'compositions')
