"""src/unicode_props.rs: the code points of the Unicode properties regexp
property escapes (`\\p{…}`) name, from test262's tests of them.

Each of test262's generated property escape tests (built-ins/RegExp/
property-escapes/generated, by unicode-property-escapes-tests) lists the
code points of one property (a binary one, a general category, a script
or script extension) and every spelling of its escape (`Script=Latin`,
`sc=Latn`, …): a table of sets (identical ones once) and of the
spellings, sorted, for `regexp::Parser::property`'s binary search.

    python3 -I scripts/unicode-props.py
"""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, 'test262/test/built-ins/RegExp/property-escapes/generated')


def ranges(body):
    lone = re.search(r'loneCodePoints: \[(.*?)\]', body, re.S).group(1)
    rng = re.search(r'ranges: \[(.*)\]', body, re.S).group(1)
    rs = [(int(a, 16), int(b, 16)) for a, b in re.findall(r'\[(0x[0-9A-Fa-f]+), (0x[0-9A-Fa-f]+)\]', rng)]
    rs += [(int(p, 16),) * 2 for p in re.findall(r'0x[0-9A-Fa-f]+', lone)]
    merged = []
    for a, b in sorted(rs):
        if merged and a <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(b, merged[-1][1]))
        else:
            merged.append((a, b))
    return merged


props = []
for f in sorted(os.listdir(D)):
    if not f.endswith('.js'):
        continue
    src = open(os.path.join(D, f)).read()
    m = re.search(r'const matchSymbols = buildString\(\{(.*?)\}\);', src, re.S)
    if not m:
        continue
    names = []
    for n in re.findall(r'/\^\\p\{([^}]*)\}\+\$/u', src):
        if n not in names:
            names.append(n)
    props.append((names, ranges(m.group(1))))

sets, order = {}, []
for _, r in props:
    if tuple(r) not in sets:
        sets[tuple(r)] = len(order)
        order.append(r)
names = sorted((n, sets[tuple(r)]) for ns, r in props for n in ns)

out = [
    "// Generated by scripts/unicode-props.py from test262's property escape",
    "// tests (Unicode 17): don't edit.",
    "",
    "/// The properties' code points: sorted inclusive ranges.",
    "pub(crate) static SETS: [&[(u32, u32)]; %d] = [" % len(order),
]
out += ['    &[' + ', '.join('(0x%X, 0x%X)' % ab for ab in r) + '],' for r in order]
out += [
    "];",
    "",
    "/// Each property escape's spelling (`Script=Latin`, `sc=Latn`, `L`, …)",
    "/// and its set in [`SETS`], sorted by spelling.",
    "pub(crate) static NAMES: [(&str, u16); %d] = [" % len(names),
]
out += ['    ("%s", %d),' % (n, i) for n, i in names]
out.append("];")
open(os.path.join(ROOT, 'src/unicode_props.rs'), 'w').write('\n'.join(out) + '\n')
print(len(props), 'properties,', len(order), 'sets,', len(names), 'names')
