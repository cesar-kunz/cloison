"""src/unicode_strings.rs: the strings of the Unicode properties of
strings (`\\p{RGI_Emoji}` and the others, in `v` mode), from test262's
tests of them.

Each of test262's generated tests of a property of strings (built-ins/
RegExp/property-escapes/generated/strings, by unicode-property-escapes-
tests) lists its strings (`matchStrings`). `RGI_Emoji` is the union of the
six others (checked here), so it isn't written out: `regexp` makes it.
Each property's strings are one `&str`, one string a line.

    python3 -I scripts/unicode-strings.py
"""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, 'test262/test/built-ins/RegExp/property-escapes/generated/strings')


def js_string(lit):
    """A JS string literal's value (the escapes these tests use)."""
    out, i = [], 0
    while i < len(lit):
        c = lit[i]
        if c != '\\':
            out.append(ord(c))
            i += 1
            continue
        e = lit[i + 1]
        if e == 'u' and lit[i + 2] == '{':
            end = lit.index('}', i)
            out.append(int(lit[i + 3:end], 16))
            i = end + 1
        elif e == 'u':
            out.append(int(lit[i + 2:i + 6], 16))
            i += 6
        elif e == 'x':
            out.append(int(lit[i + 2:i + 4], 16))
            i += 4
        else:
            out.append(ord(e))
            i += 2
    # Surrogate pairs as their code points.
    cps, i = [], 0
    while i < len(out):
        if 0xD800 <= out[i] < 0xDC00 and i + 1 < len(out) and 0xDC00 <= out[i + 1] < 0xE000:
            cps.append(0x10000 + ((out[i] - 0xD800) << 10) + (out[i + 1] - 0xDC00))
            i += 2
        else:
            cps.append(out[i])
            i += 1
    return tuple(cps)


props = {}
version = None
for f in sorted(os.listdir(D)):
    if not f.endswith('.js') or 'negative' in f:
        continue
    src = open(os.path.join(D, f)).read()
    version = version or re.search(r'Unicode v([\d.]+)', src).group(1)
    body = re.search(r'matchStrings: \[(.*?)\]', src, re.S).group(1)
    props[f[:-3]] = sorted({js_string(s) for s in re.findall(r'"((?:[^"\\]|\\.)*)"', body)})

parts = [p for p in props if p != 'RGI_Emoji']
union = sorted(set().union(*(set(props[p]) for p in parts)))
assert union == props['RGI_Emoji'], 'RGI_Emoji is not the union of the others'

with open(os.path.join(ROOT, 'src/unicode_strings.rs'), 'w') as out:
    out.write('// Generated by scripts/unicode-strings.py from test262\'s tests of the\n')
    out.write(f'// properties of strings (Unicode {version}): don\'t edit.\n\n')
    out.write('/// Each property of strings but `RGI_Emoji` (their union), by name:\n')
    out.write('/// its strings, one a line.\n')
    out.write(f'pub(crate) static STRINGS: [(&str, &str); {len(parts)}] = [\n')
    for p in sorted(parts):
        text = '\\n'.join(''.join(f'\\u{{{c:X}}}' for c in s) for s in props[p])
        out.write(f'    ("{p}", "{text}"),\n')
    out.write('];\n')
print(version, {p: len(v) for p, v in props.items()})
