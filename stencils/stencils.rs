/// Call runtime function `$f` with two boxed arguments; returns the raw
/// 64-bit result (a `Value`, or a `bool` in the low byte).
///
/// Wrapper convention (the JIT emits the wrapper, see `src/jit.rs`):
/// - x86-64: arguments in rax and r11, result in rax. The wrapper may
///   clobber r10 and r11, and xmm8–xmm15. Every caller-saved slot register
///   (rdi rsi rdx rcx r8 r9, xmm0–xmm7) is an in/out operand. LLVM keeps
///   nothing else in them across the call, and the wrapper preserves the
///   ones the region uses (the rest hold nothing). The `call` pushes a
///   return address, so the asm first steps over the 128-byte red zone.
/// - arm64: arguments in x8 and x9, result in x8. The wrapper may clobber
///   x7, x9–x17 and v16–v31; `bl` clobbers x30. x18, a temporary on Linux,
///   is clobbered too: C code may use it. Slot registers x24–x28 are
///   callee-saved under the C ABI anyway; x0–x6 and v0–v7 are in/out
///   operands.
#[cfg(target_arch = "x86_64")]
macro_rules! rt_call {
    ($s:ident, $f:ident, $a:expr, $b:expr $(; $($extra:tt)*)?) => {{
        let (mut a, b): (u64, u64) = ($a.to_bits(), $b.to_bits());
        let [mut g0, mut g1, mut g2, mut g3, mut g4, mut g5] = $s.g.map(Value::to_bits);
        let [mut f0, mut f1, mut f2, mut f3, mut f4, mut f5, mut f6] = $s.f;
        let mut facc = $s.facc;
        core::arch::asm!(
            "lea rsp, [rsp - 128]",
            "call {f}",
            "lea rsp, [rsp + 128]",
            f = sym $f,
            inout("rax") a,
            inout("r11") b => _,
            inout("rdi") g0, inout("rsi") g1, inout("rdx") g2,
            inout("rcx") g3, inout("r8") g4, inout("r9") g5,
            inout("xmm0") facc,
            inout("xmm1") f0, inout("xmm2") f1, inout("xmm3") f2, inout("xmm4") f3,
            inout("xmm5") f4, inout("xmm6") f5, inout("xmm7") f6,
            out("r10") _,
            out("xmm8") _, out("xmm9") _, out("xmm10") _, out("xmm11") _,
            out("xmm12") _, out("xmm13") _, out("xmm14") _, out("xmm15") _,
            $($($extra)*)?
        );
        $s.g = [g0, g1, g2, g3, g4, g5].map(Value::from_bits);
        $s.f = [f0, f1, f2, f3, f4, f5, f6];
        $s.facc = facc;
        a
    }};
}

#[cfg(target_arch = "aarch64")]
macro_rules! rt_call {
    ($s:ident, $f:ident, $a:expr, $b:expr $(; $($extra:tt)*)?) => {{
        let (mut a, b): (u64, u64) = ($a.to_bits(), $b.to_bits());
        let [g0, g1, g2, g3, g4, mut g5, mut g6, mut g7, mut g8, mut g9, mut g10, mut g11] =
            $s.g.map(Value::to_bits);
        let [mut f0, mut f1, mut f2, mut f3, mut f4, mut f5, mut f6] = $s.f;
        let mut facc = $s.facc;
        core::arch::asm!(
            "bl {f}",
            f = sym $f,
            inout("x8") a,
            inout("x9") b => _,
            inout("x0") g5, inout("x1") g6, inout("x2") g7, inout("x3") g8,
            inout("x4") g9, inout("x5") g10, inout("x6") g11,
            inout("v0") facc,
            inout("v1") f0, inout("v2") f1, inout("v3") f2, inout("v4") f3,
            inout("v5") f4, inout("v6") f5, inout("v7") f6,
            out("x7") _, out("x10") _, out("x11") _, out("x12") _, out("x13") _,
            out("x14") _, out("x15") _, out("x16") _, out("x17") _, out("x18") _,
            out("x30") _,
            out("v16") _, out("v17") _, out("v18") _, out("v19") _,
            out("v20") _, out("v21") _, out("v22") _, out("v23") _,
            out("v24") _, out("v25") _, out("v26") _, out("v27") _,
            out("v28") _, out("v29") _, out("v30") _, out("v31") _,
            $($($extra)*)?
        );
        $s.g = [g0, g1, g2, g3, g4, g5, g6, g7, g8, g9, g10, g11].map(Value::from_bits);
        $s.f = [f0, f1, f2, f3, f4, f5, f6];
        $s.facc = facc;
        a
    }};
}

/// `toi_rt_add(a, b)`.
macro_rules! rt_add {
    ($s:ident, $a:expr, $b:expr) => {
        Value::from_bits(rt_call!($s, toi_rt_add, $a, $b))
    };
}
/// `toi_rt_inc(a)`.
macro_rules! rt_inc {
    ($s:ident, $a:expr) => {
        Value::from_bits(rt_call!($s, toi_rt_inc, $a, Value::UNDEFINED))
    };
}
/// `toi_rt_less_than(a, b)`.
macro_rules! rt_less_than {
    ($s:ident, $a:expr, $b:expr) => {
        rt_call!($s, toi_rt_less_than, $a, $b) as u8 & 1 != 0
    };
}

/// `toi_rt_mod(a, b)`: `a % b` for any `a` and a number `b`.
macro_rules! rt_mod {
    ($s:ident, $a:expr, $b:expr) => {
        Value::from_bits(rt_call!($s, toi_rt_mod, $a, $b))
    };
}
/// `toi_rt_to_int32(a)`: ToInt32(ToNumber(a)).
macro_rules! rt_to_int32 {
    ($s:ident, $a:expr) => {
        rt_call!($s, toi_rt_to_int32, $a, Value::UNDEFINED) as u32 as i32
    };
}
/// `toi_rt_loose_eq(a, b)`: `a == b`.
macro_rules! rt_loose_eq {
    ($s:ident, $a:expr, $b:expr) => {
        rt_call!($s, toi_rt_loose_eq, $a, $b) as u8 & 1 != 0
    };
}
/// `toi_rt_to_boolean(a)`.
macro_rules! rt_to_boolean {
    ($s:ident, $a:expr) => {
        rt_call!($s, toi_rt_to_boolean, $a, Value::UNDEFINED) as u8 & 1 != 0
    };
}

/// Define a stencil function `$name` exported as `$sym`, whose body sees the
/// state as `$s: St`.
macro_rules! def_fn {
    ([$($g:ident)*] [$($f:ident)*] $(#[$m:meta])* fn $name:ident = $sym:expr; |$s:ident| $body:block) => {
        $(#[$m])*
        #[unsafe(export_name = $sym)]
        #[allow(unused_mut, unused_variables)]
        unsafe extern "rust-preserve-none" fn $name(
            acc: Value, regs: *mut Value, tag: NumberTag, ctx: *mut u32,
            $($g: Value,)* facc: f64, $($f: f64,)*
        ) -> Value {
            let mut $s = St { acc, regs, tag, ctx, g: [$($g),*], facc, f: [$($f),*] };
            unsafe { $body }
        }
    };
}

/// Tail-call `$target` with state `$s`.
macro_rules! tail_impl {
    ([$($g:ident)*] [$($f:ident)*] $target:expr, $s:expr) => {{
        let St { acc, regs, tag, ctx, g: [$($g),*], facc, f: [$($f),*] } = $s;
        become $target(acc, regs, tag, ctx, $($g,)* facc, $($f,)*)
    }};
}
macro_rules! tail {
    ($target:expr, $s:expr) => { with_slots!(tail_impl! $target, $s) };
}

/// Continue with the next stencil.
macro_rules! next {
    ($s:expr) => { tail!(toi_continue, $s) };
}
/// Take the branch.
macro_rules! jump {
    ($s:expr) => { tail!(toi_jump_target, $s) };
}
/// Side-exit before this instruction has changed anything.
macro_rules! exit {
    ($s:expr) => { tail!(toi_exit, $s) };
}
/// Go to this stencil's `__slow` helper (defined by `stencil_slow!`).
macro_rules! slow {
    ($s:expr) => { tail!(slow, $s) };
}

/// A stencil exported as `toi_stencil_<concat of $name…>`.
macro_rules! stencil {
    ($($name:expr),+ ; |$s:ident| $body:block) => {
        const _: () = {
            with_slots!(def_fn! fn main = concat!("toi_stencil_", $($name),+); |$s| $body);
        };
    };
}

/// A stencil with a cold `__slow` helper; `slow!(s)` in the fast body goes
/// there.
macro_rules! stencil_slow {
    ($($name:expr),+ ; |$s:ident| $fast:block ; |$t:ident| $slow:block) => {
        const _: () = {
            with_slots!(def_fn! fn main = concat!("toi_stencil_", $($name),+); |$s| $fast);
            with_slots!(def_fn! #[cold] #[inline(never)] fn slow = concat!("toi_stencil_", $($name),+, "__slow"); |$t| $slow);
        };
    };
}

/// The `i32` immediate operand.
#[cfg(target_arch = "x86_64")]
#[inline(always)]
fn imm() -> i32 {
    unsafe { &raw const toi_hole_imm as usize as u32 as i32 }
}

/// The immediate's low 32 bits, zero-extended.
#[cfg(target_arch = "x86_64")]
#[inline(always)]
fn imm_zext() -> u64 {
    // A single `mov eax, imm32`.
    imm() as u32 as u64
}

/// The immediate's 32 bits, zero-extended: `movz` + `movk` with absolute
/// relocations (`MOVW_UABS_G0_NC`, `G1_NC`). Unlike `adrp` + `add`, which
/// LLVM emits for a symbol address, this doesn't depend on where the JIT
/// code is (`adrp` is page-relative), and the 64-bit output tells LLVM the
/// upper bits are already zero.
#[cfg(target_arch = "aarch64")]
#[inline(always)]
fn imm_zext() -> u64 {
    let k: u64;
    unsafe {
        core::arch::asm!(
            "movz {k:w}, #:abs_g0_nc:{s}",
            "movk {k:w}, #:abs_g1_nc:{s}",
            k = out(reg) k,
            s = sym toi_hole_imm,
            options(pure, nomem, nostack),
        );
    }
    k
}

/// The `i32` immediate operand.
#[cfg(target_arch = "aarch64")]
#[inline(always)]
fn imm() -> i32 {
    imm_zext() as u32 as i32
}

/// The immediate when the JIT knows it fits 16 bits (0..=65535): a single
/// `movz`. Used by the `_k16` stencil variants.
#[cfg(target_arch = "aarch64")]
#[inline(always)]
fn imm16() -> i32 {
    let k: u64;
    unsafe {
        core::arch::asm!(
            "movz {k:w}, #:abs_g0_nc:{s}",
            k = out(reg) k,
            s = sym toi_hole_imm,
            options(pure, nomem, nostack),
        );
    }
    k as u32 as i32
}

/// A 64-bit immediate operand: `movabs` with an `R_X86_64_64` relocation.
/// (A symbol address in Rust would be truncated to 32 bits in the small
/// code model.)
#[cfg(target_arch = "x86_64")]
macro_rules! imm64_of {
    ($sym:ident) => {{
        let k: u64;
        unsafe {
            core::arch::asm!(
                "movabs {k}, offset {s}",
                k = out(reg) k,
                s = sym $sym,
                options(pure, nomem, nostack),
            );
        }
        k
    }};
}

/// A 64-bit immediate operand: `movz` + three `movk`.
#[cfg(target_arch = "aarch64")]
macro_rules! imm64_of {
    ($sym:ident) => {{
        let k: u64;
        unsafe {
            core::arch::asm!(
                "movz {k}, #:abs_g0_nc:{s}",
                "movk {k}, #:abs_g1_nc:{s}",
                "movk {k}, #:abs_g2_nc:{s}",
                "movk {k}, #:abs_g3:{s}",
                k = out(reg) k,
                s = sym $sym,
                options(pure, nomem, nostack),
            );
        }
        k
    }};
}

/// The first 64-bit immediate: `mod_smi_i`'s multiplier, or the shape a
/// property access checks.
#[inline(always)]
fn imm64() -> u64 {
    imm64_of!(toi_hole_imm64)
}

/// The second 64-bit immediate: an address (a prototype's slot, the global
/// object) or a transition's new shape.
#[inline(always)]
fn imm64b() -> u64 {
    imm64_of!(toi_hole_imm64b)
}

/// The VM register in memory named by the register hole.
#[cfg(target_arch = "x86_64")]
#[inline(always)]
unsafe fn mem(regs: *mut Value) -> *mut Value {
    // Folds into the access: `mov r12, [r13 + hole]`.
    unsafe { regs.byte_add(&raw const toi_hole_reg as usize) }
}

/// The VM register in memory named by the register hole: its byte offset
/// (< 2 KiB) fits one `movz`, so an access is `movz` + `ldr`/`str`.
#[cfg(target_arch = "aarch64")]
#[inline(always)]
unsafe fn mem(regs: *mut Value) -> *mut Value {
    let off: usize;
    unsafe {
        core::arch::asm!(
            "movz {o:x}, #:abs_g0_nc:{s}",
            o = out(reg) off,
            s = sym toi_hole_reg,
            options(pure, nomem, nostack),
        );
        regs.byte_add(off)
    }
}

/// A stencil using the immediate as `$k`, plus on arm64 a `_k16` variant
/// where it comes from a single `movz` (the JIT picks it for 0..=65535).
macro_rules! imm_variants {
    ($($name:expr),+ ; |$s:ident, $k:ident| $body:block) => {
        stencil!($($name),+; |$s| {
            let $k = imm();
            $body
        });
        #[cfg(target_arch = "aarch64")]
        stencil!($($name),+, "_k16"; |$s| {
            let $k = imm16();
            $body
        });
    };
}

/// Read or write a boxed location: `[m]` memory or `[g k]` a GPR slot.
macro_rules! get {
    ([m], $s:ident) => { *mem($s.regs) };
    ([g $k:literal], $s:ident) => { $s.g[$k] };
}
macro_rules! set {
    ([m], $s:ident, $v:expr) => { *mem($s.regs) = $v };
    ([g $k:literal], $s:ident, $v:expr) => { $s.g[$k] = $v };
}
macro_rules! loc {
    ([m]) => { "m" };
    ([g $k:literal]) => { concat!("g", $k) };
}

/// int32 view of a boxed int.
#[inline(always)]
fn int(v: Value) -> i32 {
    v.as_i32_unchecked()
}

// ---- Accumulator-only and control stencils ----

stencil!("nop"; |s| { next!(s) });
stencil!("jump"; |s| { jump!(s) });
stencil!("return"; |s| { s.acc });

// Exit stub tail: record the bytecode offset (`imm`) and return to the driver.
stencil!("exit"; |s| {
    *s.ctx = imm() as u32;
    s.acc
});

stencil!("lda_smi"; |s| {
    s.acc = Value::from_bits(s.tag.to_bits() | imm_zext());
    next!(s)
});

// `lda_smi` with an unboxed int32 result (specialized code).
imm_variants!("lda_smi_i"; |s, k| {
    #[cfg(target_arch = "x86_64")]
    {
        // Straight into acc; LLVM would go through another register.
        let _ = k;
        let v: u64;
        core::arch::asm!("mov {v:e}, offset {imm}", v = out(reg) v, imm = sym toi_hole_imm, options(pure, nomem, nostack));
        s.acc = Value::from_bits(v);
    }
    #[cfg(target_arch = "aarch64")]
    {
        s.acc = unboxed(k);
    }
    next!(s)
});

stencil_slow!("add_smi"; |s| {
    if s.tag.is_int32(s.acc)
        && let Some(sum) = int(s.acc).checked_add(imm())
    {
        s.acc = s.tag.box_i32(sum);
        next!(s)
    }
    slow!(s)
}; |s| {
    s.acc = rt_add!(s, s.acc, Value::from_i32(imm()));
    next!(s)
});

// In place: on overflow acc holds the wrapped sum, which the exit stub
// undoes (`undo_add_smi_i`), so the add is `add r12d, k; jo exit`. On
// x86-64 the immediate is part of the `add` (inline asm, with `asm goto`
// for the overflow branch); LLVM would load it into a register first.
imm_variants!("add_smi_i"; |s, k| {
    #[cfg(target_arch = "x86_64")]
    {
        let _ = k;
        let mut v = s.acc.to_bits();
        core::arch::asm!(
            "add {v:e}, offset {imm}",
            "{{disp32}} jo {ovf}",
            v = inout(reg) v,
            imm = sym toi_hole_imm,
            ovf = label { unsafe {
                s.acc = Value::from_bits(v);
                exit!(s)
            } },
            options(nomem, nostack),
        );
        s.acc = Value::from_bits(v);
        next!(s)
    }
    #[cfg(target_arch = "aarch64")]
    {
        let (v, overflow) = int(s.acc).overflowing_add(k);
        s.acc = unboxed(v);
        if overflow {
            exit!(s)
        }
        next!(s)
    }
});

