//! Copy-and-patch stencils for the baseline JIT (`src/jit.rs`).
//!
//! `build.rs` compiles this file on its own into an object file, extracts
//! each `toi_stencil_*` function's machine code and relocations, and
//! generates tables for the JIT. The JIT copies one stencil per bytecode
//! instruction (plus conversions on control-flow edges, register loads at
//! entry and spills at exits) and patches the relocations.
//!
//! Stencils are written like the interpreter handlers
//! (`extern "rust-preserve-none"`, ending in `become`), with these
//! differences:
//! - There is no `pc` and no dispatch. The next instruction is the `extern`
//!   function `toi_continue`, a relocation the JIT patches to point at the
//!   next stencil. When that stencil comes right after, the JIT drops the
//!   trailing `jmp`. Branches go to `toi_jump_target` the same way.
//! - Operands are holes: `extern` statics whose *address* is the operand
//!   (`toi_hole_imm`, `toi_hole_reg`). The JIT patches each address
//!   relocation with the operand's value. Stencils must only use the low
//!   32 bits of `toi_hole_imm`: on x86-64 the small code model may emit it
//!   sign- or zero-extended.
//! - Slow paths that call into the runtime (`toi_rt_*`) live in separate
//!   `#[cold]` helper functions named `toi_stencil_<op>__slow`. Otherwise
//!   LLVM sets up a stack frame on the fast path too. The JIT copies each
//!   instruction's helpers into a cold area.
//! - Runtime calls are inline `asm!` ([`rt_call!`]), not Rust calls: a C call
//!   clobbers the caller-saved slot registers, so LLVM would save and restore
//!   all of them around every call, even in regions that use none. Instead
//!   the asm passes every caller-saved slot register through as an in/out
//!   operand, and the call goes to a per-region wrapper that the JIT emits
//!   in JIT memory, saving only the slots that region uses.
//! - Side exits leave through `toi_exit`, patched to a per-instruction stub
//!   (spills, then the `exit` stencil). It records the instruction's
//!   bytecode offset in `*ctx` and returns `acc` to the JIT driver. An
//!   exiting stencil must not have changed any state yet.
//!
//! # Machine state (milestone 3)
//!
//! Every stencil takes the whole machine state as arguments, so it lives in
//! fixed registers throughout the generated code ([`St`]):
//!
//! | field  | x86-64            | arm64              | contents |
//! |--------|-------------------|--------------------|----------|
//! | `acc`  | r12               | x20                | accumulator when not a double: if typed int32, its low 32 bits hold the int and its high bits are 0 or the tag; otherwise boxed |
//! | `regs` | r13               | x21                | the VM register file in memory |
//! | `tag`  | r14               | x22                | `NUMBER_TAG` |
//! | `ctx`  | r15               | x23                | exit record |
//! | `g[k]` | rdi rsi rdx rcx r8 r9 | x24–x28, x0–x6 | VM registers cached in GPRs: boxed (`_g<k>`) or raw int32 (`_u<k>`) |
//! | `facc` | xmm0              | d0                 | accumulator when it is a double, unboxed |
//! | `f[k]` | xmm1–xmm7         | d1–d7              | VM registers cached in FP registers, unboxed doubles |
//!
//! `preserve_none` passes integers in up to 12 registers on x86-64 and 23 on
//! arm64; floats use the C convention's 8. x86-64 uses 6 GPR slots, leaving
//! rax, r10, r11 and rbx as scratch; arm64 has room for 12.
//!
//! A register operand can't be a hole: the machine register is part of the
//! instruction encoding. So stencils that touch a VM register come in one
//! variant per location, generated by macros below: `_m` (memory, through
//! `toi_hole_reg`), `_g<k>` (boxed), `_u<k>` (unboxed int32) and `_f<k>`.
//!
//! Naming: `<op>[_<types>]_<loc>`. Types are one letter per operand, acc
//! first: `i` int32 (boxed in a GPR or memory), `f` double. `iif` is an
//! int32 operation that overflowed before, so it produces a double. A
//! missing type part means the generic stencil (any types). A result typed
//! double goes to `facc`; an int32 result to `acc`, unboxed; anything else
//! to `acc`, boxed. Stencils reading an int32 `acc` use only its low 32
//! bits, so a boxed int32 is a valid int32 `acc` too.

