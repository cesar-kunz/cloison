// ---- Property access, fed by inline caches ----
//
// The JIT reads each property instruction's inline cache when it compiles,
// and bakes what it holds into the stencil: the receiver's shape
// (`imm64`), the slot's offset (`imm`) and, for a prototype's property or
// a transition, an address or the new shape (`imm64b`). The guard is a cell
// check and one shape compare; on a mismatch the stencil exits before the
// instruction, and the interpreter's inline cache takes over.
//
// Names: `get_own_<loc>` (`acc = [o + imm]`), `get_oop_<loc>` (`acc =
// [o.props + imm]`), `get_proto_<loc>` (`acc = [imm64b]`); `set_own_<loc>`,
// `set_oop_<loc>`, `set_tr_<loc>` (store `acc`, boxed, after writing the new
// shape); `lda_global`, `lda_global_oop`, `sta_global`, `sta_global_oop` (the
// global object is `imm64b`); `get_keyed[_i]_<loc>` (`acc = o[acc]`, a
// packed element in bounds); `guard_cell_<loc>`, `shape_jeq_<loc>`,
// `shape_jne_<loc>` and `shape_guard_<loc>` for polymorphic accesses and
// calls. `<loc>` is the receiver's
// register.

/// Whether `v` is a cell, testing against the tag register.
#[inline(always)]
fn is_cell(tag: NumberTag, v: Value) -> bool {
    v.to_bits() & tag.to_bits() == 0 && v.to_bits() & Value::OTHER_TAG == 0
}

/// The receiver `o`, if it is a cell whose shape is `imm64`.
#[inline(always)]
unsafe fn guard_shape(tag: NumberTag, o: Value) -> Option<*mut u8> {
    let p = o.to_bits() as *mut u8;
    if is_cell(tag, o) && unsafe { *(p as *const u64) } == imm64() {
        Some(p)
    } else {
        None
    }
}

/// The slot `imm` bytes into `base` (folds into the access as a
/// displacement).
#[cfg(target_arch = "x86_64")]
#[inline(always)]
unsafe fn at_imm(base: *mut u8) -> *mut Value {
    unsafe { base.byte_add(&raw const toi_hole_imm as usize).cast() }
}

/// The value `imm` bytes into `base`.
#[cfg(target_arch = "x86_64")]
#[inline(always)]
unsafe fn load_imm(base: *mut u8) -> Value {
    unsafe { *at_imm(base) }
}
#[cfg(target_arch = "x86_64")]
#[inline(always)]
unsafe fn store_imm(base: *mut u8, v: Value) {
    unsafe { *at_imm(base) = v }
}
ldst_imm!(load_imm, store_imm, toi_hole_imm, "#:lo12:{s}", "{s}@PAGEOFF");

/// The object's out-of-line slots (`Object::props`, at offset 16).
#[inline(always)]
unsafe fn props(o: *mut u8) -> *mut u8 {
    unsafe { *(o.add(16) as *const *mut u8) }
}

/// A keyed load stencil: `$ok` vets the receiver `$o`; `$int_key` says the
/// key is known to be an int32.
macro_rules! keyed_load {
    ($loc:tt, $name:literal, $int_key:literal, |$s:ident, $o:ident| $ok:expr) => {
        stencil!($name, loc!($loc); |$s| {
            let $o = get!($loc, $s);
            if !($ok) || (!$int_key && !$s.tag.is_int32($s.acc)) {
                exit!($s)
            }
            let p = $o.to_bits() as *const u8;
            let i = int($s.acc) as u32;
            if i >= *(p.add(32) as *const u32) {
                exit!($s)
            }
            let v = *(*(p.add(24) as *const *const Value)).add(i as usize);
            // x86-64: the hole check through `asm goto`, so the exit is the
            // conditional jump (folded straight to the exit stub) and the
            // continuation the final, trimmed one. LLVM otherwise ends with
            // the exit and jumps over it to the continuation.
            #[cfg(target_arch = "x86_64")]
            core::arch::asm!(
                "test {v}, {v}",
                "{{disp32}} jz {hole}",
                v = in(reg) v.to_bits(),
                hole = label { unsafe { exit!($s) } },
                options(nomem, nostack),
            );
            #[cfg(target_arch = "aarch64")]
            if v.to_bits() == 0 {
                exit!($s)
            }
            $s.acc = v;
            next!($s)
        });
    };
}

/// `o.length` for an array or string `o` at a boxed location: its
/// elements' or code units' count (`Object::elems_len`, at byte 32), after
/// a check that it is one (`Object::class` at byte 8 is `Class::Array`, 1,
/// or `Class::String`, 4) unless its shape is known (`_nc`).
macro_rules! array_length {
    ($loc:tt) => {
        stencil!("get_length_", loc!($loc); |s| {
            let o = get!($loc, s);
            if !is_cell(s.tag, o) || !matches!(*(o.to_bits() as *const u8).add(8), 1 | 4 | 7) {
                exit!(s)
            }
            s.acc = unboxed(*(o.to_bits() as *const u8).add(32).cast::<i32>());
            next!(s)
        });
        stencil!("get_length_nc_", loc!($loc); |s| {
            let o = get!($loc, s);
            s.acc = unboxed(*(o.to_bits() as *const u8).add(32).cast::<i32>());
            next!(s)
        });
    };
}
array_length!([m]);
