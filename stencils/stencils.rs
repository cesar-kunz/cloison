const G: usize = 12;
const F: usize = 7;

/// The machine state, unpacked from and repacked into stencil arguments.
/// LLVM keeps it entirely in the argument registers.
#[derive(Clone, Copy)]
struct St {
    acc: Value,
    regs: *mut Value,
    tag: NumberTag,
    ctx: *mut u32,
    g: [Value; G],
    facc: f64,
    f: [f64; F],
}

/// Calls `$m!([g idents] [f idents] rest…)` with this target's slot names.
#[cfg(target_arch = "x86_64")]
macro_rules! with_slots {
    ($m:ident ! $($t:tt)*) => { $m! { [g0 g1 g2 g3 g4 g5] [f0 f1 f2 f3 f4 f5 f6] $($t)* } };
}
#[cfg(target_arch = "aarch64")]
macro_rules! with_slots {
    ($m:ident ! $($t:tt)*) => {
        $m! { [g0 g1 g2 g3 g4 g5 g6 g7 g8 g9 g10 g11] [f0 f1 f2 f3 f4 f5 f6] $($t)* }
    };
}

