/// A stencil using the immediate as `$k`, plus on arm64 a `_k16` variant
/// where it comes from a single `movz` (the JIT picks it for 0..=65535).
macro_rules! imm_variants {
    ($($name:expr),+ ; |$s:ident, $k:ident| $body:block) => {
        stencil!($($name),+; |$s| {
            let $k = imm();
            $body
        });
        #[cfg(target_arch = "aarch64")]
        stencil!($($name),+, "_k16"; |$s| {
            let $k = imm16();
            $body
        });
    };
}

/// Read or write a boxed location: `[m]` memory or `[g k]` a GPR slot.
macro_rules! get {
    ([m], $s:ident) => { load_m($s.regs) };
    ([g $k:literal], $s:ident) => { $s.g[$k] };
}
macro_rules! set {
    ([m], $s:ident, $v:expr) => { store_m($s.regs, $v) };
    ([g $k:literal], $s:ident, $v:expr) => { $s.g[$k] = $v };
}
macro_rules! loc {
    ([m]) => { "m" };
    ([g $k:literal]) => { concat!("g", $k) };
}

/// int32 view of a boxed int.
/// `x` as a double. On x86-64 `cvtsi2sd` writes only the low half of its
/// register, so it waits for the register's last writer (LLVM doesn't break
/// the dependency here): in a loop that's often the previous iteration's
/// `divsd`. Zeroing the register first (`xorps`, free at rename) breaks
/// it. (Measured on 03-double-scale: 8.4M to 3.5M cycles.)
#[inline(always)]
fn i2f(x: i32) -> f64 {
    #[cfg(target_arch = "x86_64")]
    unsafe {
        let r: f64;
        core::arch::asm!(
            "xorps {r}, {r}",
            "cvtsi2sd {r}, {x:e}",
            r = out(xmm_reg) r,
            x = in(reg) x,
            options(pure, nomem, nostack, preserves_flags),
        );
        r
    }
    #[cfg(not(target_arch = "x86_64"))]
    {
        x as f64
    }
}

/// [`i2f`] for an `i64`.
#[inline(always)]
fn l2f(x: i64) -> f64 {
    #[cfg(target_arch = "x86_64")]
    unsafe {
        let r: f64;
        core::arch::asm!(
            "xorps {r}, {r}",
            "cvtsi2sd {r}, {x}",
            r = out(xmm_reg) r,
            x = in(reg) x,
            options(pure, nomem, nostack, preserves_flags),
        );
        r
    }
    #[cfg(not(target_arch = "x86_64"))]
    {
        x as f64
    }
}

#[inline(always)]
fn int(v: Value) -> i32 {
    v.as_i32_unchecked()
}

/// Whether boxed `v` is a number (an int32 or a double).
#[inline(always)]
fn is_num(tag: NumberTag, v: Value) -> bool {
    v.to_bits() & tag.to_bits() != 0
}

/// A boxed number's value.
#[inline(always)]
fn num(tag: NumberTag, v: Value) -> f64 {
    if tag.is_int32(v) { i2f(int(v)) } else { tag.decode_f64(v) }
}

