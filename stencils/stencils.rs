stencil!("nop"; |s| { next!(s) });
stencil!("jump"; |s| { jump!(s) });
stencil!("return"; |s| { s.acc });

// Exit stub tail: record the bytecode offset (`imm`) and return to the driver.
stencil!("exit"; |s| {
    *s.ctx = imm() as u32;
    s.acc
});

stencil!("lda_smi"; |s| {
    s.acc = Value::from_bits(s.tag.to_bits() | imm_zext());
    next!(s)
});

// `lda_smi` with an unboxed int32 result (specialized code).
imm_variants!("lda_smi_i"; |s, k| {
    #[cfg(target_arch = "x86_64")]
    {
        // Straight into acc; LLVM would go through another register.
        let _ = k;
        let v: u64;
        core::arch::asm!("mov {v:e}, offset {imm}", v = out(reg) v, imm = sym toi_hole_imm, options(pure, nomem, nostack));
        s.acc = Value::from_bits(v);
    }
    #[cfg(target_arch = "aarch64")]
    {
        s.acc = unboxed(k);
    }
    next!(s)
});

stencil_slow!("add_smi"; |s| {
    if s.tag.is_int32(s.acc)
        && let Some(sum) = int(s.acc).checked_add(imm())
    {
        s.acc = s.tag.box_i32(sum);
        next!(s)
    }
    slow!(s)
}; |s| {
    // `toi_rt_add(x, r)` is `r + x`: here `acc + k`.
    s.acc = rt_add!(s, Value::from_i32(imm()), s.acc);
    next!(s)
});

// In place: on overflow acc holds the wrapped sum, which the exit stub
// undoes (`undo_add_smi_i`), so the add is `add r12d, k; jo exit`. On
// x86-64 the immediate is part of the `add` (inline asm, with `asm goto`
// for the overflow branch); LLVM would load it into a register first.
imm_variants!("add_smi_i"; |s, k| {
    #[cfg(target_arch = "x86_64")]
    {
        let _ = k;
        let mut v = s.acc.to_bits();
        core::arch::asm!(
            "add {v:e}, offset {imm}",
            "{{disp32}} jo {ovf}",
            v = inout(reg) v,
            imm = sym toi_hole_imm,
            ovf = label { unsafe {
                s.acc = Value::from_bits(v);
                exit!(s)
            } },
            options(nomem, nostack),
        );
        s.acc = Value::from_bits(v);
        next!(s)
    }
    #[cfg(target_arch = "aarch64")]
    {
        let (v, overflow) = int(s.acc).overflowing_add(k);
        s.acc = unboxed(v);
        if overflow {
            exit!(s)
        }
        next!(s)
    }
});

// See `add_wrap_ii_*`.
imm_variants!("add_smi_wrap_i"; |s, k| {
    s.acc = unboxed(int(s.acc).wrapping_add(k));
    next!(s)
});

stencil!("undo_add_smi_i"; |s| {
    s.acc = unboxed(int(s.acc).wrapping_sub(imm()));
    next!(s)
});

stencil!("add_smi_iif"; |s| {
    s.facc = l2f(int(s.acc) as i64 + imm() as i64);
    next!(s)
});

