// `$card`: the value may be a cell, so the store needs the barrier (not
// for an int32 or a number).
macro_rules! set_keyed {
    ($loc:tt, $case:literal, $card:literal, $array:expr, |$s:ident, $v:ident, $code:ident| $fits:expr, |$t:ident| $value:expr) => {
        stencil!("set_keyed_", $case, loc!($loc); |$s| {
            let key = key_x();
            let o = get!($loc, $s);
            if !$array($s.tag, o) {
                exit!($s)
            }
            let p = o.to_bits() as *mut u8;
            let i = key as u32;
            let $v = {
                let $t = &$s;
                $value
            };
            let $code = **(p as *const *const u64);
            if i >= *(p.add(32) as *const u32) || !($fits) {
                exit!($s)
            }
            let at = (*(p.add(24) as *const *mut Value)).add(key as usize);
            *at = $v;
            if $card {
                barrier($s.tag, (*(p.add(24) as *const *const u8)).sub(8), at, $v);
            }
            next!($s)
        });
    };
}

macro_rules! property_location {
    ($loc:tt) => {
        stencil!("get_own_", loc!($loc); |s| {
            let Some(o) = guard_shape(s.tag, get!($loc, s)) else { exit!(s) };
            s.acc = load_imm(o);
            next!(s)
        });
        stencil!("get_oop_", loc!($loc); |s| {
            let Some(o) = guard_shape(s.tag, get!($loc, s)) else { exit!(s) };
            s.acc = load_imm(props(o));
            next!(s)
        });
        stencil!("get_proto_", loc!($loc); |s| {
            if guard_shape(s.tag, get!($loc, s)).is_none() {
                exit!(s)
            }
            s.acc = *(imm64b() as *const Value);
            next!(s)
        });
        stencil!("set_own_", loc!($loc); |s| {
            let Some(o) = guard_shape(s.tag, get!($loc, s)) else { exit!(s) };
            store_imm(o, s.acc);
            barrier(s.tag, o, o, s.acc);
            next!(s)
        });
        stencil!("set_oop_", loc!($loc); |s| {
            let Some(o) = guard_shape(s.tag, get!($loc, s)) else { exit!(s) };
            let p = props(o);
            store_imm(p, s.acc);
            barrier(s.tag, p.sub(8), p.offset(imm() as isize), s.acc);
            next!(s)
        });
        stencil!("set_tr_", loc!($loc); |s| {
            let Some(o) = guard_shape(s.tag, get!($loc, s)) else { exit!(s) };
            *(o as *mut u64) = imm64b();
            store_imm(o, s.acc);
            barrier(s.tag, o, o, s.acc);
            next!(s)
        });
        // `_n`: `acc` is known to be a number, never a cell: no barrier.
        stencil!("set_own_n_", loc!($loc); |s| {
            let Some(o) = guard_shape(s.tag, get!($loc, s)) else { exit!(s) };
            store_imm(o, s.acc);
            next!(s)
        });
        stencil!("set_oop_n_", loc!($loc); |s| {
            let Some(o) = guard_shape(s.tag, get!($loc, s)) else { exit!(s) };
            store_imm(props(o), s.acc);
            next!(s)
        });
        stencil!("set_tr_n_", loc!($loc); |s| {
            let Some(o) = guard_shape(s.tag, get!($loc, s)) else { exit!(s) };
            *(o as *mut u64) = imm64b();
            store_imm(o, s.acc);
            next!(s)
        });
        // `o[k] = acc`: an array (`_nc`: known to be one), an int32 key
        // within its length, a value its shape's elements' type
        // (`Shape::elems_code`, at offset 0) fits; else leave before. `acc`
        // boxed, or (`_i`) an int32, which fits codes 0 to 2, or (`_o`) an
        // object, which fits code 0 or its shape. The key in r11 / x15
        // (`key_x`); the generic stencil's at `regs + imm`, its `__slow`
        // helper (a typed array, through the runtime) reading it there too.
        stencil_slow!("set_keyed_", loc!($loc); |s| {
            let o = get!($loc, s);
            let key = load_imm(s.regs as *mut u8);
            if !is_array(s.tag, o) {
                if is_cell(s.tag, o) && *(o.to_bits() as *const u8).add(8) == 7 {
                    slow!(s)
                }
                exit!(s)
            }
            if !s.tag.is_int32(key) {
                exit!(s)
            }
            let p = o.to_bits() as *mut u8;
            let i = int(key) as u32;
            let v = s.acc;
            let code = **(p as *const *const u64);
            let fits = match code {
                0 => true,
                1 => s.tag.is_int32(v),
                2 => v.to_bits() & s.tag.to_bits() != 0,
                sh => is_cell(s.tag, v) && *(v.to_bits() as *const u64) == sh,
            };
            if i >= *(p.add(32) as *const u32) || !fits {
                exit!(s)
            }
            let at = (*(p.add(24) as *const *mut Value)).add(i as usize);
            *at = v;
            barrier(s.tag, (*(p.add(24) as *const *const u8)).sub(8), at, v);
            next!(s)
        }; |s| {
            let key = load_imm(s.regs as *mut u8);
            let args = [get!($loc, s), key, s.acc];
            let r = rt_call!(s, toi_rt_set_keyed, Value::from_bits(args.as_ptr() as u64), Value::UNDEFINED);
            if r == 0 {
                exit!(s)
            }
            next!(s)
        });
        set_keyed!($loc, "i_", false, is_array, |s, v, code| code <= 2,
            |s| Value::from_bits(s.acc.to_bits() as u32 as u64 | s.tag.to_bits()));
        set_keyed!($loc, "o_", true, is_array, |s, v, code| code == 0 || code == *(v.to_bits() as *const u64), |s| s.acc);
        set_keyed!($loc, "nc_", true, |_, _| true, |s, v, code| match code {
            0 => true,
            1 => s.tag.is_int32(v),
            2 => v.to_bits() & s.tag.to_bits() != 0,
            sh => is_cell(s.tag, v) && *(v.to_bits() as *const u64) == sh,
        }, |s| s.acc);
        set_keyed!($loc, "nc_i_", false, |_, _| true, |s, v, code| code <= 2,
            |s| Value::from_bits(s.acc.to_bits() as u32 as u64 | s.tag.to_bits()));
        set_keyed!($loc, "nc_o_", true, |_, _| true, |s, v, code| code == 0 || code == *(v.to_bits() as *const u64), |s| s.acc);
        // The array's exact shape known, so its elements' type: any
        // (`nc_a`), numbers (`nc_n`), or an int32 into int32s, numbers or
        // any (`nc_ia`): no dispatch on the code.
        set_keyed!($loc, "nc_a_", true, |_, _| true, |s, v, code| true, |s| s.acc);
        set_keyed!($loc, "nc_n_", false, |_, _| true, |s, v, code| v.to_bits() & s.tag.to_bits() != 0, |s| s.acc);
        set_keyed!($loc, "nc_ia_", false, |_, _| true, |s, v, code| true,
            |s| Value::from_bits(s.acc.to_bits() as u32 as u64 | s.tag.to_bits()));
        // A polymorphic access (`jit::Prop::Poly`): a cell check, then a
        // compare per cached shape (`imm64`), each branching to its own
        // `_nc` access but the last, which exits on a mismatch and falls
        // through to its access.
        // A load whose value is unused (`jit::Insn::check_only`): its
        // receiver's shape guard alone.
        stencil!("check_shape_", loc!($loc); |s| {
            if guard_shape(s.tag, get!($loc, s)).is_none() {
                exit!(s)
            }
            next!(s)
        });
        stencil!("guard_cell_", loc!($loc); |s| {
            if !is_cell(s.tag, get!($loc, s)) {
                exit!(s)
            }
            next!(s)
        });
        stencil!("shape_jeq_", loc!($loc); |s| {
            if *(get!($loc, s).to_bits() as *const u64) == imm64() {
                jump!(s)
            }
            next!(s)
        });
        stencil!("shape_jne_", loc!($loc); |s| {
            if *(get!($loc, s).to_bits() as *const u64) != imm64() {
                jump!(s)
            }
            next!(s)
        });
        stencil!("shape_guard_", loc!($loc); |s| {
            if *(get!($loc, s).to_bits() as *const u64) != imm64() {
                exit!(s)
            }
            next!(s)
        });
        // The same against the shape's family (`Shape::family`, at offset
        // 8): any shape differing from the cached ones in its elements'
        // type alone.
        stencil!("family_jeq_", loc!($loc); |s| {
            if *(*(get!($loc, s).to_bits() as *const *const u64)).add(1) == imm64() {
                jump!(s)
            }
            next!(s)
        });
        stencil!("family_jne_", loc!($loc); |s| {
            if *(*(get!($loc, s).to_bits() as *const *const u64)).add(1) != imm64() {
                jump!(s)
            }
            next!(s)
        });
        stencil!("family_guard_", loc!($loc); |s| {
            if *(*(get!($loc, s).to_bits() as *const *const u64)).add(1) != imm64() {
                exit!(s)
            }
            next!(s)
        });
        // The receiver's shape is known to be the cached one: no guard.
        stencil!("get_own_nc_", loc!($loc); |s| {
            s.acc = load_imm(get!($loc, s).to_bits() as *mut u8);
            next!(s)
        });
        stencil!("get_oop_nc_", loc!($loc); |s| {
            s.acc = load_imm(props(get!($loc, s).to_bits() as *mut u8));
            next!(s)
        });
        stencil!("get_proto_nc_", loc!($loc); |s| {
            s.acc = *(imm64b() as *const Value);
            next!(s)
        });
        stencil!("set_own_nc_", loc!($loc); |s| {
            let o = get!($loc, s).to_bits() as *mut u8;
            store_imm(o, s.acc);
            barrier(s.tag, o, o, s.acc);
            next!(s)
        });
        stencil!("set_tr_nc_", loc!($loc); |s| {
            let o = get!($loc, s).to_bits() as *mut u8;
            *(o as *mut u64) = imm64b();
            store_imm(o, s.acc);
            barrier(s.tag, o, o, s.acc);
            next!(s)
        });
        stencil!("set_oop_nc_", loc!($loc); |s| {
            let p = props(get!($loc, s).to_bits() as *mut u8);
            store_imm(p, s.acc);
            barrier(s.tag, p.sub(8), p.offset(imm() as isize), s.acc);
            next!(s)
        });
        stencil!("set_own_n_nc_", loc!($loc); |s| {
            store_imm(get!($loc, s).to_bits() as *mut u8, s.acc);
            next!(s)
        });
        stencil!("set_tr_n_nc_", loc!($loc); |s| {
            let o = get!($loc, s).to_bits() as *mut u8;
            *(o as *mut u64) = imm64b();
            store_imm(o, s.acc);
            next!(s)
        });
        stencil!("set_oop_n_nc_", loc!($loc); |s| {
            store_imm(props(get!($loc, s).to_bits() as *mut u8), s.acc);
            next!(s)
        });
        // Elements at offset 24, length (u32) at 32. A hole is `EMPTY` (0).
        // `_i`: the key is known to be an int32. `_nc`: the receiver is
        // known to be an object; `_sh`: its shape must be `imm64` (the
        // elements' type comes with it).
        // An object whose elements are values: not a string (class 4, at
        // byte 8: code units), a buffer or a typed array (6 and 7: bytes).
        keyed_load!($loc, "get_keyed_i_", true, |s, o| is_cell(s.tag, o)
            && matches!(*(o.to_bits() as *const u8).add(8), 0..=3 | 5));
        keyed_load!($loc, "get_keyed_", false, |s, o| is_cell(s.tag, o)
            && matches!(*(o.to_bits() as *const u8).add(8), 0..=3 | 5));
        // `acc = o[acc]` through the runtime (`acc` boxed): a typed array's
        // element, or a site whose receivers the fast ones keep leaving
        // for. Leaves only where it would throw or call a function.
        // `o[k] = acc` through the runtime (`jit::Prop::Runtime`), the key
        // from memory, at `regs + imm`; `acc` boxed, or (`_i`) an int32.
        // (An object's own element first, as the interpreter's
        // `op_set_keyed` stores it: see `own_element_store`.)
        stencil_slow!("set_keyed_rt_", loc!($loc); |s| {
            if own_element_store(s.tag, get!($loc, s), load_imm(s.regs as *mut u8), s.acc, false) {
                next!(s)
            }
            slow!(s)
        }; |s| {
            let key = load_imm(s.regs as *mut u8);
            let args = [get!($loc, s), key, s.acc];
            // Not merged with `set_keyed_`'s identical helper: each stencil
            // must keep its own.
            core::arch::asm!(concat!("/* set_keyed_rt_", loc!($loc), " */"), options(nomem, nostack, preserves_flags));
            let r = rt_call!(s, toi_rt_set_keyed, Value::from_bits(args.as_ptr() as u64), Value::UNDEFINED);
            if r == 0 {
                exit!(s)
            }
            next!(s)
        });
        stencil_slow!("set_keyed_rt_i_", loc!($loc); |s| {
            let v = Value::from_bits(s.acc.to_bits() as u32 as u64 | s.tag.to_bits());
            if own_element_store(s.tag, get!($loc, s), load_imm(s.regs as *mut u8), v, true) {
                next!(s)
            }
            slow!(s)
        }; |s| {
            let key = load_imm(s.regs as *mut u8);
            let v = Value::from_bits(s.acc.to_bits() as u32 as u64 | s.tag.to_bits());
            let args = [get!($loc, s), key, v];
            let r = rt_call!(s, toi_rt_set_keyed, Value::from_bits(args.as_ptr() as u64), Value::UNDEFINED);
            if r == 0 {
                exit!(s)
            }
            next!(s)
        });
        // (An object's own element first, as `get_keyed_`.)
        stencil_slow!("get_keyed_rt_", loc!($loc); |s| {
            let o = get!($loc, s);
            if is_cell(s.tag, o)
                && s.tag.is_int32(s.acc)
                && matches!(*(o.to_bits() as *const u8).add(8), 0..=3 | 5)
            {
                let p = o.to_bits() as *const u8;
                let i = int(s.acc) as u32;
                if i < *(p.add(32) as *const u32) {
                    let v = *(*(p.add(24) as *const *const Value)).add(i as usize);
                    if v.to_bits() != 0 {
                        s.acc = v;
                        next!(s)
                    }
                }
            }
            slow!(s)
        }; |s| {
            let r = rt_call!(s, toi_rt_get_keyed, get!($loc, s), s.acc);
            if r == 0 {
                exit!(s)
            }
            s.acc = Value::from_bits(r);
            next!(s)
        });
        keyed_load!($loc, "get_keyed_i_nc_", true, |s, o| true);
        keyed_load!($loc, "get_keyed_nc_", false, |s, o| true);
        keyed_load!($loc, "get_keyed_i_sh_", true, |s, o| guard_shape(s.tag, o).is_some());
        keyed_load!($loc, "get_keyed_sh_", false, |s, o| guard_shape(s.tag, o).is_some());
    };
}

