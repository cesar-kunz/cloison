// ---- Stencils on a boxed location: memory (`_m`) or a GPR slot (`_g<k>`) ----

macro_rules! boxed_location {
    ($loc:tt) => {
        stencil!("ldar_", loc!($loc); |s| {
            s.acc = get!($loc, s);
            next!(s)
        });
        stencil!("ldar_", loc!($loc), "_f"; |s| {
            s.facc = s.tag.decode_f64(get!($loc, s));
            next!(s)
        });
        stencil!("star_", loc!($loc); |s| {
            set!($loc, s, s.acc);
            next!(s)
        });
        // Store an int32 acc, which may be unboxed, into a boxed location.
        // Box acc in place (a boxed int32 is still a valid int32 acc):
        // boxing into a scratch register costs an extra `mov` on x86-64.
        stencil!("star_", loc!($loc), "_i"; |s| {
            s.acc = s.tag.rebox(s.acc);
            set!($loc, s, s.acc);
            next!(s)
        });
        stencil!("star_", loc!($loc), "_f"; |s| {
            set!($loc, s, s.tag.encode_f64(s.facc));
            next!(s)
        });
        // int32 → double in place, where a join widened the type.
        stencil!("conv_", loc!($loc), "_f"; |s| {
            set!($loc, s, s.tag.encode_f64(i2f(int(get!($loc, s)))));
            next!(s)
        });

        stencil_slow!("add_", loc!($loc); |s| {
            let rhs = get!($loc, s);
            if s.tag.both_int32(s.acc, rhs)
                && let Some(sum) = int(s.acc).checked_add(int(rhs))
            {
                s.acc = s.tag.box_i32(sum);
                next!(s)
            }
            slow!(s)
        }; |s| {
            let rhs = get!($loc, s);
            // Two numbers (an int32 overflow, a double): their sum, as the
            // runtime gives it, without calling it.
            if is_num(s.tag, s.acc) && is_num(s.tag, rhs) {
                s.acc = s.tag.encode_f64(num(s.tag, rhs) + num(s.tag, s.acc));
                next!(s)
            }
            s.acc = rt_add!(s, s.acc, rhs);
            next!(s)
        });
        stencil!("add_ii_", loc!($loc); |s| {
            match int(s.acc).checked_add(int(get!($loc, s))) {
                Some(sum) => {
                    s.acc = unboxed(sum);
                    next!(s)
                }
                None => exit!(s),
            }
        });
        // An add whose result only feeds a bitwise operation (ToInt32):
        // `(a + b) | 0` is the wrapping add, so no overflow check.
        stencil!("add_wrap_ii_", loc!($loc); |s| {
            s.acc = unboxed(int(s.acc).wrapping_add(int(get!($loc, s))));
            next!(s)
        });
        stencil!("add_iif_", loc!($loc); |s| {
            s.facc = l2f(int(s.acc) as i64 + int(get!($loc, s)) as i64);
            next!(s)
        });
        stencil!("add_if_", loc!($loc); |s| {
            s.facc = i2f(int(s.acc)) + s.tag.decode_f64(get!($loc, s));
            next!(s)
        });
        stencil!("add_fi_", loc!($loc); |s| {
            s.facc += i2f(int(get!($loc, s)));
            next!(s)
        });
        stencil!("add_ff_", loc!($loc); |s| {
            s.facc += s.tag.decode_f64(get!($loc, s));
            next!(s)
        });

        stencil_slow!("jlt_", loc!($loc); |s| {
            let rhs = get!($loc, s);
            if !s.tag.both_int32(s.acc, rhs) {
                slow!(s)
            }
            if int(s.acc) < int(rhs) {
                jump!(s)
            }
            next!(s)
        }; |s| {
            let rhs = get!($loc, s);
            if rt_less_than!(s, s.acc, rhs) {
                jump!(s)
            }
            next!(s)
        });
        stencil!("jlt_ii_", loc!($loc); |s| {
            if int(s.acc) < int(get!($loc, s)) {
                jump!(s)
            }
            next!(s)
        });
        stencil!("jlt_if_", loc!($loc); |s| {
            if i2f(int(s.acc)) < s.tag.decode_f64(get!($loc, s)) {
                jump!(s)
            }
            next!(s)
        });
        stencil!("jlt_fi_", loc!($loc); |s| {
            if s.facc < i2f(int(get!($loc, s))) {
                jump!(s)
            }
            next!(s)
        });
        stencil!("jlt_ff_", loc!($loc); |s| {
            if s.facc < s.tag.decode_f64(get!($loc, s)) {
                jump!(s)
            }
            next!(s)
        });
    };
}

