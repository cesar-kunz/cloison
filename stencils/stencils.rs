// A store's value against its field's type (`object::FieldType`), when the
// value's type doesn't prove it fits: exit before the store, so the
// interpreter generalizes the field.
stencil!("check_acc_int"; |s| {
    if !s.tag.is_int32(s.acc) {
        exit!(s)
    }
    next!(s)
});
stencil!("check_acc_num"; |s| {
    if s.acc.to_bits() & s.tag.to_bits() == 0 {
        exit!(s)
    }
    next!(s)
});
stencil!("check_acc_shape"; |s| {
    if !is_cell(s.tag, s.acc) || *(s.acc.to_bits() as *const u64) != imm64() {
        exit!(s)
    }
    next!(s)
});

// A number loaded from a field typed `Num`, into `facc`.
stencil!("unbox_num_acc"; |s| {
    s.facc = if s.tag.is_int32(s.acc) {
        i2f(int(s.acc))
    } else {
        s.tag.decode_f64(s.acc)
    };
    next!(s)
});

// ---- Calls ----

// A call through the runtime (`toi_rt_call`), described by the call site
// at `imm64`; the callee's arguments are in memory (the JIT spills them).
// The runtime returns `EMPTY` on an error: leave, and the run ends. If the
// VM's code epoch (at `imm64b`) isn't `imm` anymore, the callee changed
// something the code assumes: leave too, after the call.
stencil!("call"; |s| {
    let regs = Value::from_bits(s.regs as u64);
    let r = Value::from_bits(rt_call!(s, toi_rt_call, regs, Value::from_bits(imm64())));
    s.acc = r;
    // The exit is after the call: `acc` holds the result.
    if r.to_bits() == 0 || *(imm64b() as *const u32) != imm() as u32 {
        exit!(s)
    }
    next!(s)
});

/// The part of a call site (`jit::CallSite`, `repr(C)`) that `call_direct`
/// and `construct_direct` read. Offsets are in bytes from the caller's
/// registers.
#[repr(C)]
struct DirectSite {
    /// The callee's compiled entry; 0: call through the runtime.
    entry: u64,
    /// The function compiled: the callee register must hold it.
    closure: u64,
    f_off: u64,
    /// Where the callee's compiled frame ends: before `stack_end`.
    end_off: u64,
    stack_end: u64,
    native_limit: u64,
    this_shape: u64,
    /// For `new`: how to allocate `this` (null if not a direct `new`).
    ctor: *mut CtorAlloc,
}

/// `jit::CtorSite`: how `construct_direct` allocates `this`.
#[repr(C)]
struct CtorAlloc {
    /// The VM heap's free space (`heap::Heap::bump`).
    heap: *mut HeapPtrs,
    proto_at: *const u64,
    proto: u64,
    cap_at: *const u32,
    cap: u64,
    slots: u64,
    this_off: u64,
    done_shape: u64,
    header: [u64; 6],
}

/// `rt_call!` to `toi_rt_enter`, whose wrapper (`arch::enter_wrapper` in
/// `src/jit.rs`) passes the tag and `ctx` registers on to the callee and
/// doesn't preserve `acc`'s. So they must hold the tag and `ctx` at the
/// call: LLVM otherwise only keeps them across it, free to use them in
/// between (and `construct_direct` does).
#[cfg(target_arch = "x86_64")]
macro_rules! rt_call_enter {
    ($s:ident, $f:ident, $a:expr, $b:expr) => {{
        let tag: u64 = core::mem::transmute($s.tag);
        rt_call!($s, $f, $a, $b; out("r12") _, in("r14") tag, in("r15") $s.ctx,)
    }};
}
#[cfg(target_arch = "aarch64")]
macro_rules! rt_call_enter {
    ($s:ident, $f:ident, $a:expr, $b:expr) => {{
        let tag: u64 = core::mem::transmute($s.tag);
        rt_call!($s, $f, $a, $b; out("x20") _, in("x22") tag, in("x23") $s.ctx,)
    }};
}

// A call straight into the callee's compiled code (`toi_rt_enter`, which
// checks the native stack), whose frame the compiled code has set up, if
// the call site (`DirectSite` at `imm64`) has an entry, the callee
// register holds the function compiled, and the VM stack has room;
// otherwise through the runtime, as `call`. Leave after it as `call` does
// (`imm64b` is the code's epoch, which must still be `imm`).
stencil!("call_direct"; |s| {
    let regs = Value::from_bits(s.regs as u64);
    let site = imm64() as *const DirectSite;
    let base = s.regs as *const u8;
    let r = if (*site).entry != 0
        && *(base.add((*site).f_off as usize) as *const u64) == (*site).closure
        && base as u64 + (*site).end_off <= (*site).stack_end
    {
        Value::from_bits(rt_call_enter!(s, toi_rt_enter, regs, Value::from_bits(site as u64)))
    } else {
        Value::from_bits(rt_call!(s, toi_rt_call, regs, Value::from_bits(site as u64)))
    };
    s.acc = r;
    if r.to_bits() == 0 || *(imm64b() as *const u32) != imm() as u32 {
        exit!(s)
    }
    next!(s)
});

// `call_direct` where the callee register is known to hold the site's
// closure (a guard on it passed): without that check.
stencil!("call_direct_nc"; |s| {
    let regs = Value::from_bits(s.regs as u64);
    let site = imm64() as *const DirectSite;
    let base = s.regs as *const u8;
    let r = if (*site).entry != 0 && base as u64 + (*site).end_off <= (*site).stack_end {
        Value::from_bits(rt_call_enter!(s, toi_rt_enter, regs, Value::from_bits(site as u64)))
    } else {
        Value::from_bits(rt_call!(s, toi_rt_call, regs, Value::from_bits(site as u64)))
    };
    s.acc = r;
    if r.to_bits() == 0 || *(imm64b() as *const u32) != imm() as u32 {
        exit!(s)
    }
    next!(s)
});

// After a direct call the JIT made without the `toi_rt_enter` wrapper
// (`arch::direct_call` in `src/jit.rs`), its result in `acc`: leave as
// `call_direct` does.
stencil!("call_done"; |s| {
    if s.acc.to_bits() == 0 || *(imm64b() as *const u32) != imm() as u32 {
        exit!(s)
    }
    next!(s)
});

// `new`, as `call_direct`, allocating `this` itself: if what the
// constructor's root shape depends on is unchanged and the heap's chunk
// has room, bump the heap, write the header, put
// `this` in the callee's frame and enter. The result is the
// constructor's, if an object, else `this`, after `construct_done`
// (`toi_rt_construct_done`) unless that has nothing to do for its shape.
// Otherwise `toi_rt_construct` allocates and enters.
stencil!("construct_direct"; |s| {
    let regs = Value::from_bits(s.regs as u64);
    let site = imm64() as *const DirectSite;
    let base = s.regs as *const u8;
    let r = if (*site).entry != 0
        && *(base.add((*site).f_off as usize) as *const u64) == (*site).closure
        && base as u64 + (*site).end_off <= (*site).stack_end
    {
        let c = (*site).ctor;
        if *(*c).proto_at == (*c).proto
            && *(*c).cap_at as u64 == (*c).cap
            && let Some(p) = bump((*c).heap, 6 + (*c).slots as usize)
        {
            // The header only: a slot is read only through a shape that
            // has its property, and a store writes the slot no later than
            // the shape (a hole's memory is zero meanwhile).
            for k in 0..6 {
                *p.add(k) = (*c).header[k];
            }
            *(base.add((*c).this_off as usize) as *mut u64) = p as u64;
            let v = Value::from_bits(rt_call_enter!(s, toi_rt_enter, regs, Value::from_bits(site as u64)));
            if v.to_bits() == 0 || v.is_cell() {
                v
            } else {
                if *p != (*c).done_shape {
                    rt_call!(s, toi_rt_construct_done, Value::from_bits(site as u64), Value::from_bits(p as u64));
                }
                Value::from_bits(p as u64)
            }
        } else {
            Value::from_bits(rt_call!(s, toi_rt_construct, regs, Value::from_bits(site as u64)))
        }
    } else {
        Value::from_bits(rt_call!(s, toi_rt_call, regs, Value::from_bits(site as u64)))
    };
    s.acc = r;
    if r.to_bits() == 0 || *(imm64b() as *const u32) != imm() as u32 {
        exit!(s)
    }
    next!(s)
});

// Before an inlined `new`: the constructor's `prototype` slot (at
// `imm64`) still holds `imm64b`, the prototype of the shape the inlined
// body assumes; else leave before the `new`.
// In an exit stub: the register at `regs + reg hole` is `imm64` (a value
// compiled code knew and didn't write; see `jit::Insn::exit_const`).
// At an entry of compiled code: zero `imm` registers from byte `imm64`
// of the frame, dead there (a register compiled code keeps elsewhere, an
// inlined frame's), whose words would otherwise hold whatever an earlier
// frame left: the collector scans them, and a stale pointer keeps what it
// reaches alive (Splay's removed nodes, each pointing at the next).
stencil!("clear_m"; |s| {
    let p = (s.regs as *mut u8).add(imm64() as usize) as *mut u64;
    let n = imm() as usize;
    // Two words a store (`stp xzr, xzr`). Volatile: not a call to
    // `memset`, which a stencil can't make.
    let mut k = 0;
    while k + 2 <= n {
        p.add(k).cast::<u128>().write_volatile(0);
        k += 2;
    }
    if k < n {
        p.add(k).write_volatile(0);
    }
    next!(s)
});
// Jump if the words at `imm64` and `imm64b` differ (at an entry: whether
// a collection ran since the code last zeroed its dead registers).
stencil!("words_jne"; |s| {
    if *(imm64() as *const u64) != *(imm64b() as *const u64) {
        jump!(s)
    }
    next!(s)
});
// Copy the word at `imm64` to `imm64b`.
stencil!("copy_word"; |s| {
    *(imm64b() as *mut u64) = *(imm64() as *const u64);
    next!(s)
});
// `clear_m` for one register (at `regs + reg hole`): one `str xzr`.
stencil!("zero_m"; |s| {
    store_m(s.regs, Value::EMPTY);
    next!(s)
});
stencil!("store_const_m"; |s| {
    store_m(s.regs, Value::from_bits(imm64_full()));
    next!(s)
});

// At a loop header of warm code (see `jit::Tier`): count down the
// function's heat (an `i64` at `imm64`); when it runs out, leave at the
// header to tier up.
stencil!("tier_count"; |s| {
    let heat = imm64() as *mut i64;
    *heat -= 1;
    if *heat < 0 {
        exit!(s)
    }
    next!(s)
});

stencil!("guard_word"; |s| {
    if *(imm64() as *const u64) != imm64b_full() {
        exit!(s)
    }
    next!(s)
});

// An inlined `new` whose object scalar replacement doesn't allocate: the
// check `guard_word` makes, then `acc` = `undefined`.
stencil!("ctor_check"; |s| {
    if *(imm64() as *const u64) != imm64b_full() {
        exit!(s)
    }
    s.acc = Value::UNDEFINED;
    next!(s)
});

// In an exit: allocate an object scalar replacement left unallocated
// (`imm64` describes it, `jit::Mat`), from the spilled registers.
stencil!("materialize"; |s| {
    rt_call!(s, toi_rt_materialize, Value::from_bits(s.regs as u64), Value::from_bits(imm64()));
    next!(s)
});

// `a.push(v)` (`a` in its slot, `v` in `acc`, boxed; `_i`: an int32): a
// store at the end and the length bumped, if `a` is an array (else leave
// before the call; `_nc`: known to be one) whose elements have room and
// whose shape's elements' type (`Shape::elems_code`, at offset 0) `v`
// fits; otherwise the runtime pushes (growing the elements, moving `a` to a
// more general shape). `acc` = the new length, an int32.
// `a.pop()` (`a` in its slot): the last element, its slot made a hole and
// the length one less, or `undefined` if empty (or a hole), if `a` is an
// array; else leave before the call.
/// `vm::NO_ELEMENTS`: the elements' code of a shape with no elements yet.
const NO_ELEMENTS: u64 = 3;
/// `object::PUSH_WAYS`, and the word of `object::PushCache::any`.
const PUSH_WAYS: usize = 4;
const PUSH_ANY: usize = 2 * PUSH_WAYS;

/// The elements a push's helper gives an array without any (as a new one).
/// In Octane's DeltaBlue, 7.3M of 8.9M pushes through the runtime were the
/// first onto an array; allocating them with every array instead cost
/// 20-constructor-fields 46%.
const FIRST_ELEMENTS: usize = 4;

/// If the array at `o` has no room for elements at all, give it
/// [`FIRST_ELEMENTS`] (`undefined`) from the heap's free space (`imm64`:
/// `Heap::bump`), if there is that much: an array cell, its header word
/// (`heap::VALUES`, the capacity) and the values.
#[inline(always)]
unsafe fn first_elements(o: *mut u8) {
    if *(o.add(36) as *const u32) != 0 {
        return;
    }
    let heap = imm64() as *mut HeapPtrs;
    if heap.is_null() {
        return;
    }
    let Some(p) = bump(heap, 1 + FIRST_ELEMENTS) else { return };
    *p = 1 | (FIRST_ELEMENTS as u64) << 32;
    let p = p.add(1);
    // Volatile: LLVM would vectorize the stores from a constant pool,
    // which a stencil can't refer to.
    for k in 0..FIRST_ELEMENTS {
        p.add(k).write_volatile(Value::UNDEFINED.to_bits());
    }
    *(o.add(24) as *mut *mut u64) = p;
    // (A young array: only an old array needs the card.)
    if meta_of(o as usize) != YOUNG {
        card_mark(o);
    }
    *(o.add(36) as *mut u32) = FIRST_ELEMENTS as u32;
}

/// For a push of `v` that doesn't fit the elements of an array of `shape`
/// (with room for it): the shape the array moves to, if a push of the same
/// kind of value made that transition before (`Shape::push`, an
/// `object::PushCache`), else 0. An int32 onto int32 elements fits; another
/// number generalizes them to numbers, which is left to the runtime.
#[inline(always)]
unsafe fn push_transition(tag: NumberTag, shape: *const u64, v: Value) -> u64 {
    let code = *shape;
    // `Shape::push`, an `object::PushCache`.
    let cache = *shape.add(2) as *const u64;
    if cache.is_null() {
        return 0;
    }
    let number = v.to_bits() & tag.to_bits() != 0;
    if code == NO_ELEMENTS {
        let key = if tag.is_int32(v) {
            1
        } else if number {
            2
        } else if is_cell(tag, v) {
            *(v.to_bits() as *const u64)
        } else {
            0
        };
        push_target(cache, key)
    } else if code == 1 && number || code == 0 {
        0
    } else {
        *cache.add(PUSH_ANY)
    }
}

/// The shape `PushCache::to` (at `cache`) moves an array to for a value of
/// key `key`, or 0.
#[inline(always)]
unsafe fn push_target(cache: *const u64, key: u64) -> u64 {
    let mut to = 0;
    for k in 0..PUSH_WAYS {
        if to == 0 && *cache.add(2 * k) == key {
            to = *cache.add(2 * k + 1);
        }
    }
    to
}

/// `o[key] = v` for an object `o` whose elements' type
/// (`Shape::elems_code`) fits `v`, `key` an int32 within its elements, as
/// the interpreter's `op_set_keyed` stores it (`int32`: `v` is one,
/// which codes 0 to 2 fit). False, storing nothing, otherwise.
#[inline(always)]
unsafe fn own_element_store(tag: NumberTag, o: Value, key: Value, v: Value, int32: bool) -> bool {
    if !is_cell(tag, o) || !tag.is_int32(key) {
        return false;
    }
    let p = o.to_bits() as *mut u8;
    unsafe {
        let fits = match **(p as *const *const u64) {
            code if int32 => code <= 2,
            0 => true,
            1 => tag.is_int32(v),
            2 => v.to_bits() & tag.to_bits() != 0,
            sh => is_cell(tag, v) && *(v.to_bits() as *const u64) == sh,
        };
        let i = int(key) as u32;
        if !fits || i >= *(p.add(32) as *const u32) {
            return false;
        }
        let at = (*(p.add(24) as *const *mut Value)).add(i as usize);
        *at = v;
        if !int32 {
            barrier(tag, (*(p.add(24) as *const *const u8)).sub(8), at, v);
        }
        true
    }
}

#[inline(always)]
fn is_array(tag: NumberTag, a: Value) -> bool {
    is_cell(tag, a) && unsafe { *(a.to_bits() as *const u8).add(8) } == 1
}
macro_rules! array_methods {
    ($loc:tt, $nc:literal, $array:expr) => {
        stencil_slow!("array_push_", $nc, loc!($loc); |s| {
            let a = get!($loc, s);
            let v = s.acc;
            if !$array(s.tag, a) {
                exit!(s)
            }
            let o = a.to_bits() as *mut u8;
            let fits = match **(o as *const *const u64) {
                0 => true,
                1 => s.tag.is_int32(v),
                2 => v.to_bits() & s.tag.to_bits() != 0,
                sh => is_cell(s.tag, v) && *(v.to_bits() as *const u64) == sh,
            };
            let len = *(o.add(32) as *const u32);
            if !fits || len >= *(o.add(36) as *const u32) {
                slow!(s)
            }
            let at = (*(o.add(24) as *const *mut Value)).add(len as usize);
            *at = v;
            barrier(s.tag, (*(o.add(24) as *const *const u8)).sub(8), at, v);
            *(o.add(32) as *mut u32) = len + 1;
            s.acc = unboxed(len as i32 + 1);
            next!(s)
        }; |s| {
            // Each stencil keeps its own helper (LLVM would merge these).
            core::arch::asm!(concat!("/* array_push_", $nc, loc!($loc), " */"), options(nomem, nostack, preserves_flags));
            let a = get!($loc, s);
            let v = s.acc;
            let o = a.to_bits() as *mut u8;
            let len = *(o.add(32) as *const u32);
            first_elements(o);
            if len < *(o.add(36) as *const u32) {
                let to = push_transition(s.tag, *(o as *const *const u64), v);
                if to != 0 {
                    *(o as *mut u64) = to;
                    let at = (*(o.add(24) as *const *mut Value)).add(len as usize);
                    *at = v;
                    barrier(s.tag, (*(o.add(24) as *const *const u8)).sub(8), at, v);
                    *(o.add(32) as *mut u32) = len + 1;
                    s.acc = unboxed(len as i32 + 1);
                    next!(s)
                }
            }
            s.acc = unboxed(int(Value::from_bits(rt_call!(s, toi_rt_array_push, a, v))));
            next!(s)
        });
        // An int32 fits elements of any type but objects of a shape
        // (codes 0 to 2; `NO_ELEMENTS` is 3, a shape's address more).
        stencil_slow!("array_push_i_", $nc, loc!($loc); |s| {
            let a = get!($loc, s);
            if !$array(s.tag, a) {
                exit!(s)
            }
            let o = a.to_bits() as *mut u8;
            let len = *(o.add(32) as *const u32);
            if **(o as *const *const u64) > 2 || len >= *(o.add(36) as *const u32) {
                slow!(s)
            }
            *(*(o.add(24) as *const *mut u64)).add(len as usize) = s.acc.to_bits() as u32 as u64 | s.tag.to_bits();
            *(o.add(32) as *mut u32) = len + 1;
            s.acc = unboxed(len as i32 + 1);
            next!(s)
        }; |s| {
            core::arch::asm!(concat!("/* array_push_i_", $nc, loc!($loc), " */"), options(nomem, nostack, preserves_flags));
            let a = get!($loc, s);
            let v = Value::from_bits(s.acc.to_bits() as u32 as u64 | s.tag.to_bits());
            let o = a.to_bits() as *mut u8;
            let len = *(o.add(32) as *const u32);
            first_elements(o);
            if len < *(o.add(36) as *const u32) {
                let to = push_transition(s.tag, *(o as *const *const u64), v);
                if to != 0 {
                    *(o as *mut u64) = to;
                    *(*(o.add(24) as *const *mut Value)).add(len as usize) = v;
                    *(o.add(32) as *mut u32) = len + 1;
                    s.acc = unboxed(len as i32 + 1);
                    next!(s)
                }
            }
            s.acc = unboxed(int(Value::from_bits(rt_call!(s, toi_rt_array_push, a, v))));
            next!(s)
        });
        stencil!("array_pop_", $nc, loc!($loc); |s| {
            let a = get!($loc, s);
            if !$array(s.tag, a) {
                exit!(s)
            }
            let o = a.to_bits() as *mut u8;
            let len = *(o.add(32) as *const u32);
            s.acc = Value::UNDEFINED;
            if len != 0 {
                let at = (*(o.add(24) as *const *mut Value)).add(len as usize - 1);
                let v = *at;
                *at = Value::EMPTY;
                *(o.add(32) as *mut u32) = len - 1;
                if v != Value::EMPTY {
                    s.acc = v;
                }
            }
            next!(s)
        });
    };
    ($loc:tt) => {
        array_methods!($loc, "", is_array);
        array_methods!($loc, "nc_", |_, _| true);
    };
}
