// ---- Typed arrays' elements ----
//
// `o[acc]` and `o[k] = acc` for a typed array `o` of a known element kind
// (`jit::typed_kind`): `elems` (byte 24) points to its first element,
// `elems_len` (byte 32) is its length. An index out of bounds exits (the
// interpreter reads `undefined`, stores nothing). `_chk` first checks that
// `o` is a typed array (`class`, byte 8, 7) of the kind the inline cache
// saw (`kind`, byte 10): the word at byte 8, its flags (byte 9) masked
// off, is `imm`, `7 | kind << 16`.

/// The typed array at `o` and its element `i`'s address, `size` bytes
/// each, if `i` is in bounds.
#[inline(always)]
unsafe fn typed_elem(o: Value, i: u32, size: usize) -> Option<*mut u8> {
    let p = o.to_bits() as *const u8;
    if i >= unsafe { *(p.add(32) as *const u32) } {
        return None;
    }
    Some(unsafe { elem_at(*(p.add(24) as *const *mut u8), i, size) })
}

/// Element `i` of `size` bytes at `elems`, indexed through a pointer of
/// that size: on arm64 the load or store then scales the index itself
/// (`ldrh w20, [x8, w20, uxtw #1]`, not `ubfiz` first).
#[inline(always)]
unsafe fn elem_at(elems: *mut u8, i: u32, size: usize) -> *mut u8 {
    unsafe {
        match size {
            1 => elems.add(i as usize),
            2 => elems.cast::<u16>().add(i as usize).cast(),
            4 => elems.cast::<u32>().add(i as usize).cast(),
            _ => elems.cast::<u64>().add(i as usize).cast(),
        }
    }
}

/// Whether `o` is a typed array of kind `k`: class and kind, its bytes 8
/// and 10, are `want` (`7 | k << 16`).
#[inline(always)]
unsafe fn is_typed(tag: NumberTag, o: Value, want: u32) -> bool {
    let p = o.to_bits() as *const u8;
    is_cell(tag, o) && unsafe { *(p.add(8) as *const u32) & 0xff00ff == want }
}

macro_rules! typed_load {
    ($loc:tt, $w:literal, $size:literal, |$s:ident, $e:ident| $set:expr) => {
        stencil!("tget_", $w, "_", loc!($loc); |$s| {
            let Some($e) = typed_elem(get!($loc, $s), int($s.acc) as u32, $size) else { exit!($s) };
            $set;
            next!($s)
        });
        stencil!("tget_", $w, "_chk_", loc!($loc); |$s| {
            let o = get!($loc, $s);
            if !is_typed($s.tag, o, imm() as u32) {
                exit!($s)
            }
            let Some($e) = typed_elem(o, int($s.acc) as u32, $size) else { exit!($s) };
            $set;
            next!($s)
        });
    };
}

macro_rules! typed_store {
    ($loc:tt, $w:literal, $size:literal, |$s:ident, $e:ident| $store:expr) => {
        stencil!("tset_", $w, "_", loc!($loc); |$s| {
            let key = key_x();
            let Some($e) = typed_elem_x(get!($loc, $s), key, $size) else { exit!($s) };
            $store;
            next!($s)
        });
        stencil!("tset_", $w, "_chk_", loc!($loc); |$s| {
            let key = key_x();
            let o = get!($loc, $s);
            if !is_typed($s.tag, o, imm() as u32) {
                exit!($s)
            }
            let Some($e) = typed_elem_x(o, key, $size) else { exit!($s) };
            $store;
            next!($s)
        });
    };
}

/// As [`typed_elem`], for a key from [`key_x`].
#[inline(always)]
unsafe fn typed_elem_x(o: Value, i: u64, size: usize) -> Option<*mut u8> {
    let p = o.to_bits() as *const u8;
    // (A 32-bit compare: the key's high half is zero.)
    if i as u32 >= unsafe { *(p.add(32) as *const u32) } {
        return None;
    }
    Some(unsafe { elem_at(*(p.add(24) as *const *mut u8), i as u32, size) })
}

// ---- A keyed store's key in a scratch register ----
//
// `tset_*` takes the key in r11 / x15, zero-extended, which the JIT's
// `key_*` piece right before it sets from wherever the key lives (an
// int32 slot, a boxed one, memory), so the store stencils needn't come in
// a variant per key slot. Nothing between them touches the register.

/// The key a `key_*` piece left: the stencil's first instruction must
/// read it (checked in the disassembly; the asm has side effects, so the
/// stencil's loads and exits come after it).
#[inline(always)]
fn key_x() -> u64 {
    let k: u64;
    unsafe {
        #[cfg(target_arch = "x86_64")]
        core::arch::asm!("/* key in r11 */", out("r11") k, options(nostack, preserves_flags));
        #[cfg(target_arch = "aarch64")]
        core::arch::asm!("/* key in x15 */", out("x15") k, options(nostack, preserves_flags));
    }
    k
}

/// Leave int32 `i` in the key register, zero-extended.
#[inline(always)]
fn set_key_x(i: i32) {
    unsafe {
        #[cfg(target_arch = "x86_64")]
        core::arch::asm!("mov r11d, {i:e}", i = in(reg) i, out("r11") _, options(nostack, preserves_flags));
        #[cfg(target_arch = "aarch64")]
        core::arch::asm!("mov w15, {i:w}", i = in(reg) i, out("x15") _, options(nostack, preserves_flags));
    }
}

/// Exit unless `$v` is an int32. On x86-64 `cmp v, r14; jb exit` through
/// `asm goto` with a long `jb`, which `build.rs` aims at the exit itself
/// (`fold_x86_stubs`); LLVM's short jump would reach it through a stub at
/// the end, after the hot path's final `jmp`, which then couldn't be
/// trimmed.
macro_rules! exit_unless_int32 {
    ($s:ident, $v:expr) => {{
        #[cfg(target_arch = "x86_64")]
        core::arch::asm!(
            "cmp {v}, {t}",
            "{{disp32}} jb {bad}",
            v = in(reg) $v.to_bits(),
            t = in(reg) $s.tag.to_bits(),
            bad = label { unsafe { exit!($s) } },
            options(nomem, nostack),
        );
        #[cfg(target_arch = "aarch64")]
        if !$s.tag.is_int32($v) {
            exit!($s)
        }
    }};
}

stencil!("key_m"; |s| {
    let k = load_m(s.regs);
    exit_unless_int32!(s, k);
    set_key_x(int(k));
    next!(s)
});
macro_rules! key_gpr {
    ($k:tt) => {
        stencil!("key_g", $k; |s| {
            exit_unless_int32!(s, s.g[$k]);
            set_key_x(int(s.g[$k]));
            next!(s)
        });
        stencil!("key_u", $k; |s| {
            set_key_x(raw(s.g[$k]));
            next!(s)
        });
    };
}
with_gprs!(each_gpr! key_gpr);

macro_rules! typed_location {
    ($loc:tt) => {
        typed_load!($loc, "i8", 1, |s, e| s.acc = unboxed(*(e as *const i8) as i32));
        typed_load!($loc, "u8", 1, |s, e| s.acc = unboxed(*e as i32));
        typed_load!($loc, "i16", 2, |s, e| s.acc = unboxed(*(e as *const i16) as i32));
        typed_load!($loc, "u16", 2, |s, e| s.acc = unboxed(*(e as *const u16) as i32));
        typed_load!($loc, "i32", 4, |s, e| s.acc = unboxed(*(e as *const i32)));
        // A uint32 past int32 exits; once it has, `u32f` gives a double.
        typed_load!($loc, "u32", 4, |s, e| {
            let v = *(e as *const u32);
            if v as i32 >= 0 {
                s.acc = unboxed(v as i32)
            } else {
                exit!(s)
            }
        });
        typed_load!($loc, "u32f", 4, |s, e| s.facc = *(e as *const u32) as f64);
        typed_load!($loc, "f32", 4, |s, e| s.facc = *(e as *const f32) as f64);
        typed_load!($loc, "f64", 8, |s, e| s.facc = *(e as *const f64));

        // An int32 `acc` (`_i`) or a double in `facc` (`_f`); into an
        // integer kind, a double ToInt32 can't truncate exits.
        typed_store!($loc, "b8_i", 1, |s, e| *e = int(s.acc) as u8);
        typed_store!($loc, "b16_i", 2, |s, e| *(e as *mut u16) = int(s.acc) as u16);
        typed_store!($loc, "b32_i", 4, |s, e| *(e as *mut i32) = int(s.acc));
        typed_store!($loc, "c8_i", 1, |s, e| *e = int(s.acc).clamp(0, 255) as u8);
        typed_store!($loc, "f32_i", 4, |s, e| *(e as *mut f32) = int(s.acc) as f32);
        typed_store!($loc, "f64_i", 8, |s, e| *(e as *mut f64) = i2f(int(s.acc)));
        typed_store!($loc, "b8_f", 1, |s, e| {
            let Some(v) = f64_to_int32(s.facc) else { exit!(s) };
            *e = v as u8
        });
        typed_store!($loc, "b16_f", 2, |s, e| {
            let Some(v) = f64_to_int32(s.facc) else { exit!(s) };
            *(e as *mut u16) = v as u16
        });
        typed_store!($loc, "b32_f", 4, |s, e| {
            let Some(v) = f64_to_int32(s.facc) else { exit!(s) };
            *(e as *mut i32) = v
        });
        typed_store!($loc, "f32_f", 4, |s, e| *(e as *mut f32) = s.facc as f32);
        typed_store!($loc, "f64_f", 8, |s, e| *(e as *mut f64) = s.facc);
    };
}
macro_rules! typed_gpr {
    ($k:tt) => {
        typed_location!([g $k]);
    };
}
typed_location!([m]);
with_gprs!(each_gpr! typed_gpr);

// ---- Upvalues ----
//
// A cell (`vm::Upvalue`) points (`at`, its first field) to the variable: a
// register of the frame defining it while that runs, the cell's own slot
// after. `lda_upvalue` finds cell `imm` of the frame's function (in the
// frame header, `FUNC_OFF` bytes below the registers): `imm` is the cell's
// byte offset in the function object, after its in-object slots, which
// every function object with upvalues has as many of (`Vm::upvalues`).
// `_c`: the cell at `imm64`.

/// `interp::FUNC_OFF` (the JIT checks they agree).
const FUNC_OFF: usize = 80;

/// The upvalue (its payload: `at`, then `closed`) of the frame's function.
#[inline(always)]
unsafe fn upvalue_cell(regs: *mut Value) -> *const *mut Value {
    unsafe {
        let f = *(regs.byte_sub(FUNC_OFF) as *const *mut u8);
        load_imm(f).to_bits() as *const *mut Value
    }
}

// Before a direct call to a function with upvalues: the function object
// (`imm64`) into the callee frame's header, `imm` bytes from the registers.
stencil!("set_frame_func"; |s| {
    *((s.regs as *mut u8).offset(imm() as isize) as *mut u64) = imm64();
    next!(s)
});
stencil!("lda_upvalue"; |s| {
    s.acc = **upvalue_cell(s.regs);
    next!(s)
});
stencil!("sta_upvalue"; |s| {
    let u = upvalue_cell(s.regs);
    **u = s.acc;
    upvalue_barrier(s.tag, u, s.acc);
    next!(s)
});
stencil!("lda_upvalue_c"; |s| {
    s.acc = **(imm64() as *const *const Value);
    next!(s)
});
stencil!("sta_upvalue_c"; |s| {
    let u = imm64() as *const *mut Value;
    **u = s.acc;
    upvalue_barrier(s.tag, u, s.acc);
    next!(s)
});

stencil!("lda_global"; |s| {
    let g = imm64b() as *mut u8;
    if *(g as *const u64) != imm64() {
        exit!(s)
    }
    s.acc = load_imm(g);
    next!(s)
});
stencil!("lda_global_oop"; |s| {
    let g = imm64b() as *mut u8;
    if *(g as *const u64) != imm64() {
        exit!(s)
    }
    s.acc = load_imm(props(g));
    next!(s)
});
stencil!("sta_global"; |s| {
    let g = imm64b() as *mut u8;
    if *(g as *const u64) != imm64() {
        exit!(s)
    }
    store_imm(g, s.acc);
    barrier(s.tag, g, g, s.acc);
    next!(s)
});
stencil!("sta_global_oop"; |s| {
    let g = imm64b() as *mut u8;
    if *(g as *const u64) != imm64() {
        exit!(s)
    }
    let p = props(g);
    store_imm(p, s.acc);
    barrier(s.tag, p.sub(8), p.offset(imm() as isize), s.acc);
    next!(s)
});

// An instruction the JIT doesn't compile (a call, `return` in a VM frame,
// an allocation, an uncached property access): leave for the interpreter.
stencil!("bail"; |s| { exit!(s) });

