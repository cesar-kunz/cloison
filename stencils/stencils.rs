// ---- Unboxed int32 slots (`_u<k>`) ----
//
// A VM register that is only ever int32 in a region lives in its GPR slot as
// a raw int32, zero-extended. These stencils use the same machine registers
// as `_g<k>` but skip boxing: the value is boxed (`or tag`) only when it
// leaves the slot, for `acc`, a spill or a generic operation.

/// The int32 in an unboxed slot.
#[inline(always)]
fn raw(v: Value) -> i32 {
    v.to_bits() as u32 as i32
}

/// An int32 as an unboxed slot value (zero-extended).
#[inline(always)]
fn unboxed(i: i32) -> Value {
    Value::from_bits(i as u32 as u64)
}

macro_rules! int_slot {
    ($k:tt) => {
        // acc typed int32 may be unboxed, so this is a plain move.
        stencil!("ldar_u", $k; |s| {
            s.acc = s.g[$k];
            next!(s)
        });
        stencil!("star_u", $k; |s| {
            s.g[$k] = unboxed(int(s.acc));
            next!(s)
        });
        stencil!("enter_u", $k; |s| {
            s.g[$k] = load_m_unboxed(s.regs);
            next!(s)
        });
        // A boxed value no int32 (see `star_u<k>_v`): its high half isn't
        // zero.
        stencil!("star_u", $k, "_v"; |s| {
            s.g[$k] = s.acc;
            next!(s)
        });
        stencil!("spill_u", $k; |s| {
            store_m(s.regs, s.tag.rebox(s.g[$k]));
            next!(s)
        });
        // Where the slot may hold such a boxed value (exits, writing back
        // every slot): boxed only if its high half is zero.
        stencil!("spill_u", $k, "_v"; |s| {
            let v = s.g[$k];
            store_m(s.regs, if v.to_bits() >> 32 == 0 { s.tag.rebox(v) } else { v });
            next!(s)
        });

        stencil_slow!("add_u", $k; |s| {
            if s.tag.is_int32(s.acc)
                && let Some(sum) = int(s.acc).checked_add(raw(s.g[$k]))
            {
                s.acc = s.tag.box_i32(sum);
                next!(s)
            }
            slow!(s)
        }; |s| {
            let rhs = s.tag.box_i32(raw(s.g[$k]));
            s.acc = rt_add!(s, s.acc, rhs);
            next!(s)
        });
        stencil!("add_ii_u", $k; |s| {
            match int(s.acc).checked_add(raw(s.g[$k])) {
                Some(sum) => {
                    s.acc = unboxed(sum);
                    next!(s)
                }
                None => exit!(s),
            }
        });
        stencil!("add_wrap_ii_u", $k; |s| {
            s.acc = unboxed(int(s.acc).wrapping_add(raw(s.g[$k])));
            next!(s)
        });
        stencil!("add_iif_u", $k; |s| {
            s.facc = l2f(int(s.acc) as i64 + raw(s.g[$k]) as i64);
            next!(s)
        });
        stencil!("add_fi_u", $k; |s| {
            s.facc += i2f(raw(s.g[$k]));
            next!(s)
        });

        stencil_slow!("jlt_u", $k; |s| {
            if !s.tag.is_int32(s.acc) {
                slow!(s)
            }
            if int(s.acc) < raw(s.g[$k]) {
                jump!(s)
            }
            next!(s)
        }; |s| {
            let rhs = s.tag.box_i32(raw(s.g[$k]));
            if rt_less_than!(s, s.acc, rhs) {
                jump!(s)
            }
            next!(s)
        });
        stencil!("jlt_ii_u", $k; |s| {
            if int(s.acc) < raw(s.g[$k]) {
                jump!(s)
            }
            next!(s)
        });
        stencil!("jlt_fi_u", $k; |s| {
            if s.facc < i2f(raw(s.g[$k])) {
                jump!(s)
            }
            next!(s)
        });

        // Fused, in place. On overflow the slot holds the wrapped result;
        // the exit stub undoes it (`undo_addi_u`) before spilling, so the
        // exit still happens "before" the instruction. Writing the slot
        // first lets the add happen in place: `add edi, k; jo exit`.
        imm_variants!("addi_u", $k; |s, k| {
            #[cfg(target_arch = "x86_64")]
            {
                let _ = k;
                let mut v = s.g[$k].to_bits();
                core::arch::asm!(
                    "add {v:e}, offset {imm}",
                    "{{disp32}} jo {ovf}",
                    v = inout(reg) v,
                    imm = sym toi_hole_imm,
                    ovf = label { unsafe {
                        s.g[$k] = Value::from_bits(v);
                        exit!(s)
                    } },
                    options(nomem, nostack),
                );
                s.g[$k] = Value::from_bits(v);
                next!(s)
            }
            #[cfg(target_arch = "aarch64")]
            {
                let (v, overflow) = raw(s.g[$k]).overflowing_add(k);
                s.g[$k] = unboxed(v);
                if overflow {
                    exit!(s)
                }
                next!(s)
            }
        });
        stencil!("undo_addi_u", $k; |s| {
            s.g[$k] = unboxed(raw(s.g[$k]).wrapping_sub(imm()));
            next!(s)
        });
        imm_variants!("incjlt_u", $k; |s, k| {
            let (v, overflow) = raw(s.g[$k]).overflowing_add(1);
            s.g[$k] = unboxed(v);
            if overflow {
                exit!(s)
            }
            #[cfg(target_arch = "x86_64")]
            {
                let _ = k;
                core::arch::asm!(
                    "cmp {v:e}, offset {imm}",
                    "{{disp32}} jl {taken}",
                    v = in(reg) s.g[$k].to_bits(),
                    imm = sym toi_hole_imm,
                    taken = label { unsafe { jump!(s) } },
                    options(nomem, nostack),
                );
                next!(s)
            }
            #[cfg(target_arch = "aarch64")]
            {
                if v < k {
                    jump!(s)
                }
                next!(s)
            }
        });
    };
}

macro_rules! int_slot_pair {
    ($a:tt, $b:tt) => {
        // In place, wrapped on overflow (the exit stub undoes it). On x86-64
        // in asm: LLVM picks the wrong destination and needs two extra
        // moves (`mov rax, rsi; mov esi, edi; add esi, eax`).
        stencil!("addr_ii_u", $a, "_u", $b; |s| {
            #[cfg(target_arch = "x86_64")]
            {
                let mut v = s.g[$a].to_bits();
                core::arch::asm!(
                    "add {v:e}, {b:e}",
                    "{{disp32}} jo {ovf}",
                    v = inout(reg) v,
                    b = in(reg) s.g[$b].to_bits(),
                    ovf = label { unsafe {
                        s.g[$a] = Value::from_bits(v);
                        exit!(s)
                    } },
                    options(nomem, nostack),
                );
                s.g[$a] = Value::from_bits(v);
                next!(s)
            }
            #[cfg(target_arch = "aarch64")]
            {
                let (v, overflow) = raw(s.g[$a]).overflowing_add(raw(s.g[$b]));
                s.g[$a] = unboxed(v);
                if overflow {
                    exit!(s)
                }
                next!(s)
            }
        });
        stencil!("undo_addr_u", $a, "_u", $b; |s| {
            s.g[$a] = unboxed(raw(s.g[$a]).wrapping_sub(raw(s.g[$b])));
            next!(s)
        });
        stencil!("incjlt_u", $a, "_u", $b; |s| {
            let (v, overflow) = raw(s.g[$a]).overflowing_add(1);
            s.g[$a] = unboxed(v);
            if overflow {
                exit!(s)
            }
            if v < raw(s.g[$b]) {
                jump!(s)
            }
            next!(s)
        });
    };
}

